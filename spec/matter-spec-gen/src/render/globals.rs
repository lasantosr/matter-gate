type Result<T, E = Error> = StdResult<T, E>;

pub(crate) fn generate_single_global_tokens(
    global_defs: &GlobalDefs,
    target_name: &str,
    shared_plan: &SharedPlan,
) -> Result<Tokens> {
    let GlobalDefs {
        enums,
        bitmaps,
        structs,
        attributes,
        ..
    } = global_defs;
    let mut out = Tokens::new();
    let global_hashes = compute_global_hashes(global_defs);

    if let Some(enm) = enums.iter().find(|e| e.name == target_name) {
        out.append(quote! {
            // AUTO-GENERATED BY cargo xtask codegen-spec - DO NOT EDIT MANUALLY
        });
        out.push();
        emit_enums(&mut out, slice::from_ref(enm), None)?;
        return Ok(out);
    }

    if let Some(bm) = bitmaps.iter().find(|b| b.name == target_name) {
        out.append(quote! {
            // AUTO-GENERATED BY cargo xtask codegen-spec - DO NOT EDIT MANUALLY
        });
        out.push();
        emit_bitmaps(&mut out, slice::from_ref(bm), None)?;
        return Ok(out);
    }

    if let Some(st) = structs.iter().find(|s| s.name == target_name) {
        let mut dep_idents = BTreeSet::new();
        for f in &st.fields {
            if f.type_str != target_name
                && let Some(h) = global_hashes.get(&f.type_str)
                && let Some(ident) = shared_plan.global_ident(h)
            {
                dep_idents.insert(ident);
            }
            if let Some(et) = f.entry_type.as_deref()
                && et != target_name
                && let Some(h) = global_hashes.get(et)
                && let Some(ident) = shared_plan.global_ident(h)
            {
                dep_idents.insert(ident);
            }
        }
        out.append(quote! {
            // AUTO-GENERATED BY cargo xtask codegen-spec - DO NOT EDIT MANUALLY
            #[allow(unused_imports, reason = "Generated global imports")]
            use alloc::{string::String, vec::Vec};
            #[allow(unused_imports, reason = "Generated global imports")]
            use crate::{
                types,
                model::{
                    ActionId, AttributeId, AttributeValue, ClusterId, CommandId, DataVersion, DeviceTypeId,
                    EndpointId, EventId, EventNumber, FabricId, FabricIndex, FieldId, GroupId, MatterStatus, NodeId,
                    Nullable, Optional, TransactionId, VendorId,
                },
            };
            #[cfg(feature = $(quoted("serde")))]
            #[allow(unused_imports, reason = "Generated global imports")]
            use serde::{Deserialize, Serialize};
            $(for &ident in &dep_idents join ($['\r']) =>
                use crate::__shared::globals::$ident::*;
            )
        });
        out.push();

        let all_enums_map: BTreeMap<String, EnumDef> = enums.iter().map(|e| (e.name.clone(), e.clone())).collect();
        let all_bitmaps_map: BTreeMap<String, BitmapDef> =
            bitmaps.iter().map(|b| (b.name.clone(), b.clone())).collect();
        let all_structs_map: BTreeMap<String, StructDef> =
            structs.iter().map(|s| (s.name.clone(), s.clone())).collect();
        let ctx = TypeContext::new(
            attributes,
            enums,
            bitmaps,
            structs,
            global_defs,
            &all_enums_map,
            &all_bitmaps_map,
            &all_structs_map,
        );
        emit_structs(&mut out, slice::from_ref(st), false, &ctx, None)?;
        return Ok(out);
    }

    Err(Error::Parse(format!("Unknown global item '{target_name}'")))
}

pub(crate) fn generate_globals_tokens(
    global_defs: &GlobalDefs,
    version: &str,
    shared_plan: Option<&SharedPlan>,
) -> Result<Tokens> {
    let GlobalDefs {
        enums,
        bitmaps,
        structs,
        attributes,
        cfg_gates,
        ..
    } = global_defs;
    let mut out = Tokens::new();
    let global_hashes = compute_global_hashes(global_defs);

    let is_shared = |name: &str| -> Option<&str> {
        let ghash = global_hashes.get(name)?;
        let plan = shared_plan?;
        plan.global_ident(ghash)
    };

    let local_bitmaps: Vec<BitmapDef> = bitmaps
        .iter()
        .filter(|b| is_shared(&b.name).is_none())
        .cloned()
        .collect();
    let local_enums: Vec<EnumDef> = enums.iter().filter(|e| is_shared(&e.name).is_none()).cloned().collect();
    let local_structs: Vec<StructDef> = structs
        .iter()
        .filter(|s| is_shared(&s.name).is_none())
        .cloned()
        .collect();

    let header =
        format!("// AUTO-GENERATED BY cargo xtask codegen-spec (Matter Spec: {version}) - DO NOT EDIT MANUALLY");
    let intro = format!("//! Global enums, bitmaps, structs, and attributes for Matter {version}.");

    let globals_header: Tokens = quote! {
        $header
        $intro

        #[allow(unused_imports, reason = "Generated global imports")]
        use alloc::{string::String, vec::Vec};

        #[allow(unused_imports, reason = "Generated global imports")]
        use crate::{
            error::AttributeError,
            model::{
                ActionId, Attribute, AttributeId, AttributeValue, ClusterId, CommandId, DataVersion, DeviceTypeId,
                EndpointId, EventId, EventNumber, FabricId, FabricIndex, FieldId, GroupId, MatterStatus, NodeId,
                Nullable, Optional, TransactionId, VendorId,
            },
            types,
        };
        $(if !local_structs.is_empty() =>
            #[cfg(feature = $(quoted("serde")))]
            #[allow(unused_imports, reason = "Generated global imports")]
            use serde::{Deserialize, Serialize};
        )

        $(if !attributes.is_empty() =>
            $(format!("// Global attributes defined: {}", attributes.len()))
        )
    };
    out.append(globals_header);
    out.push();

    for name in bitmaps
        .iter()
        .map(|b| b.name.as_str())
        .chain(enums.iter().map(|e| e.name.as_str()))
        .chain(structs.iter().map(|s| s.name.as_str()))
    {
        if let Some(ident) = is_shared(name) {
            let gate_attr = cfg_gates.get(name).and_then(|g| emit_cfg_gate_attr(g));
            out.append(quote! {
                $gate_attr
                pub use crate::__shared::globals::$ident::*;
            });
        }
    }
    out.push_blank();

    if !local_bitmaps.is_empty() {
        emit_bitmaps(&mut out, &local_bitmaps, Some(cfg_gates))?;
    }
    if !local_enums.is_empty() {
        emit_enums(&mut out, &local_enums, Some(cfg_gates))?;
    }
    if !local_structs.is_empty() {
        let all_enums_map: BTreeMap<String, EnumDef> = enums.iter().map(|e| (e.name.clone(), e.clone())).collect();
        let all_bitmaps_map: BTreeMap<String, BitmapDef> =
            bitmaps.iter().map(|b| (b.name.clone(), b.clone())).collect();
        let all_structs_map: BTreeMap<String, StructDef> =
            structs.iter().map(|s| (s.name.clone(), s.clone())).collect();
        let ctx = TypeContext::new(
            attributes,
            enums,
            bitmaps,
            structs,
            global_defs,
            &all_enums_map,
            &all_bitmaps_map,
            &all_structs_map,
        );
        emit_structs(&mut out, &local_structs, false, &ctx, Some(cfg_gates))?;
    }

    // Global Attributes
    let has_event_list = attributes
        .iter()
        .any(|attr| attr.name.eq_ignore_ascii_case("EventList") || attr.code == 0xFFFA);

    let global_attributes_mod = emit_global_attributes_submodule(has_event_list);
    out.append(global_attributes_mod);
    out.push_blank();

    Ok(out)
}

fn emit_global_id_list_attr(name: &str, item_id: &str, attr_id_hex: &str) -> Tokens {
    quote! {
        $(format!("/// {name} global attribute."))
        #[derive(Debug, Clone, PartialEq, Eq, Hash, Default)]
        #[cfg_attr(feature = $(quoted("serde")), derive(Serialize, Deserialize), serde(transparent))]
        #[cfg_attr(feature = $(quoted("schemars")), derive(schemars::JsonSchema), schemars(transparent))]
        pub struct $name(Vec<$item_id>);

        impl $name {
            pub const ATTRIBUTE_ID: AttributeId = AttributeId::new($attr_id_hex);
            pub const CLUSTER_ID: ClusterId = ClusterId::WILDCARD;
            pub const NAME: &'static str = $(quoted(name));
            pub const IS_NULLABLE: bool = false;
            pub const IS_WRITABLE: bool = false;
            pub const IS_OPTIONAL: bool = false;

            #[inline]
            #[must_use]
            pub fn new(val: Vec<$item_id>) -> Self { Self(val) }

            #[inline]
            #[must_use]
            pub fn raw(&self) -> &[$item_id] { &self.0 }

            #[inline]
            #[must_use]
            pub const fn as_inner(&self) -> &Vec<$item_id> { &self.0 }

            #[inline]
            #[must_use]
            pub fn into_inner(self) -> Vec<$item_id> { self.0 }

            #[must_use]
            pub fn into_value(self) -> AttributeValue {
                let items = self.0.into_iter().map(AttributeValue::from).collect();
                AttributeValue::List(items)
            }

            pub fn try_from_value(val: AttributeValue) -> Result<Self, MatterStatus> {
                let AttributeValue::List(items) = val else {
                    return Err(MatterStatus::InvalidDataType);
                };
                let res = items.into_iter().map($item_id::try_from).collect::<Result<Vec<_>, _>>()?;
                Ok(Self(res))
            }

            pub fn validate(attr: Attribute) -> Result<Attribute, AttributeError> {
                Self::try_from(attr).map(Into::into)
            }
        }

        impl From<$name> for Attribute {
            #[inline]
            fn from(attr: $name) -> Self {
                Self::new($name::ATTRIBUTE_ID, attr.into_value())
            }
        }

        impl TryFrom<Attribute> for $name {
            type Error = AttributeError;

            fn try_from(attr: Attribute) -> Result<Self, Self::Error> {
                if attr.id != Self::ATTRIBUTE_ID {
                    return Err(AttributeError::AttributeIdMismatch {
                        expected: Self::ATTRIBUTE_ID,
                        actual: attr.id,
                    });
                }
                Self::try_from_value(attr.value).map_err(|status| AttributeError::InvalidValue {
                    id: Self::ATTRIBUTE_ID,
                    field_id: None,
                    status,
                })
            }
        }

        impl From<Vec<$item_id>> for $name {
            #[inline]
            fn from(val: Vec<$item_id>) -> Self {
                Self(val)
            }
        }

        impl From<$name> for Vec<$item_id> {
            #[inline]
            fn from(attr: $name) -> Self {
                attr.0
            }
        }

        impl ops::Deref for $name {
            type Target = Vec<$item_id>;

            #[inline]
            fn deref(&self) -> &Self::Target {
                &self.0
            }
        }

        impl AsRef<Vec<$item_id>> for $name {
            #[inline]
            fn as_ref(&self) -> &Vec<$item_id> {
                &self.0
            }
        }

        impl AsRef<[$item_id]> for $name {
            #[inline]
            fn as_ref(&self) -> &[$item_id] {
                &self.0
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                write!(f, "<list of {} items>", self.0.len())
            }
        }
    }
}

