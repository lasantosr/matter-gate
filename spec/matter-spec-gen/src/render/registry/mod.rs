/// Renders `#[cfg(feature = "registry")]` static `SpecRegistry` descriptor tables
/// for a sorted slice of clusters and device types.
pub(crate) fn render_registry_tables(
    version: &str,
    clusters: &[&ClusterDef],
    device_types: &[&ParsedDeviceType],
    global_defs: &GlobalDefs,
    all_enums: &BTreeMap<String, EnumDef>,
    all_bitmaps: &BTreeMap<String, BitmapDef>,
    all_structs: &BTreeMap<String, StructDef>,
) -> Result<String, Error> {
    let mut sorted_clusters: Vec<&ClusterDef> = clusters.to_vec();
    sorted_clusters.sort_by_key(|c| c.code);

    let mut sorted_devices: Vec<&ParsedDeviceType> = device_types.to_vec();
    sorted_devices.sort_by_key(|d| d.device_id);

    let cluster_by_name: BTreeMap<&str, &ClusterDef> = clusters.iter().map(|c| (c.name.as_str(), *c)).collect();
    let expects_event_list = global_defs.has_event_list
        || global_defs
            .attributes
            .iter()
            .any(|attr| attr.name.eq_ignore_ascii_case("EventList") || attr.code == 0xFFFA);
    let expects_event_list_str = if expects_event_list { "true" } else { "false" };

    let mut cluster_descs = Vec::with_capacity(sorted_clusters.len());
    for c in &sorted_clusters {
        cluster_descs.push(render_cluster_descriptor(
            c,
            global_defs,
            all_enums,
            all_bitmaps,
            all_structs,
        )?);
    }

    let tokens = quote! {
        $(format!("// AUTO-GENERATED BY cargo xtask codegen-spec (Matter Spec: {version}) - DO NOT EDIT MANUALLY"))
        $("//! Static read-only metadata and validation registry for Matter clusters, endpoints, and nodes.")

        #[allow(unused_imports, reason = "Generated registry imports")]
        use crate::{
            model::{
                AttributeId, ClusterId, CommandDirection, CommandId, DeviceTypeId, EventId, EventPriority, FieldId,
            },
            registry::{
                AccessFlags, AccessPrivilege, AttributeDescriptor, ChoiceGroup, ClusterDescriptor, CommandDescriptor,
                ConformanceOp, DeviceClusterReq, DeviceTypeDescriptor, DeviceTypeIncludeItem, EventDescriptor,
                FieldDescriptor, ListLength, QualityFlags, RegistryValidator, SpecRegistry, StructDescriptor,
                ValueBounds, ValueConstraint, ValueType,
            },
        };

        /// Static cluster descriptors sorted by [`ClusterId`].
        #[rustfmt::skip]
        static CLUSTERS: &[ClusterDescriptor] = &[
            $(for desc in &cluster_descs join ($['\r']) => $desc)
        ];

        /// Static device type descriptors sorted by [`DeviceTypeId`].
        #[rustfmt::skip]
        static DEVICE_TYPES: &[DeviceTypeDescriptor] = &[
            $(for d in &sorted_devices join ($['\r']) =>
                $(render_device_type_descriptor(version, d, &cluster_by_name)?)
            )
        ];

        /// Read-only static schema registry for this Matter specification release.
        pub static SPEC_REGISTRY: SpecRegistry = SpecRegistry {
            expects_event_list: $expects_event_list_str,
            clusters: CLUSTERS,
            device_types: DEVICE_TYPES,
        };

        /// Versioned validator bound to [`SPEC_REGISTRY`].
        pub struct Validator;

        impl Validator {
            /// Returns a [`RegistryValidator`] configured for [`ValidationMode::FullSnapshot`](crate::registry::ValidationMode::FullSnapshot)
            /// (`enforce_provisional: false`) against [`SPEC_REGISTRY`].
            #[must_use]
            #[inline]
            pub const fn full() -> RegistryValidator<'static> {
                RegistryValidator::full(&SPEC_REGISTRY)
            }

            /// Returns a [`RegistryValidator`] configured for [`ValidationMode::Partial`](crate::registry::ValidationMode::Partial)
            /// against [`SPEC_REGISTRY`].
            #[must_use]
            #[inline]
            pub const fn partial() -> RegistryValidator<'static> {
                RegistryValidator::partial(&SPEC_REGISTRY)
            }
        }
    };

    render(tokens)
}

fn command_direction_expr(dir: CommandDirection) -> &'static str {
    match dir {
        CommandDirection::ClientToServer => "CommandDirection::ClientToServer",
        CommandDirection::ServerToClient => "CommandDirection::ServerToClient",
    }
}

fn event_priority_expr(event_name: &str, priority: &str) -> Result<Tokens, Error> {
    match priority.to_ascii_lowercase().as_str() {
        "critical" => Ok(quote!(EventPriority::Critical)),
        "info" => Ok(quote!(EventPriority::Info)),
        "debug" => Ok(quote!(EventPriority::Debug)),
        other => Err(Error::UnknownEventPriority {
            event: event_name.to_owned(),
            priority: other.to_owned(),
        }),
    }
}

fn access_flags_expr(a: &AccessFlags) -> Tokens {
    let mut bits: u8 = 0;
    if a.read {
        bits |= 1 << 0;
    }
    if a.write {
        bits |= 1 << 1;
    }
    if a.fabric_scoped {
        bits |= 1 << 2;
    }
    if a.fabric_sensitive {
        bits |= 1 << 3;
    }
    if a.timed {
        bits |= 1 << 4;
    }
    if a.invoke {
        bits |= 1 << 6;
    }
    quote!(AccessFlags($bits))
}

fn quality_flags_expr(q: QualityFlags) -> Tokens {
    let mut bits: u8 = 0;
    if q.change_omitted {
        bits |= 1 << 0;
    }
    if q.large_message {
        bits |= 1 << 1;
    }
    if q.atomic_write {
        bits |= 1 << 2;
    }
    if q.reportable {
        bits |= 1 << 3;
    }
    quote!(QualityFlags($bits))
}

fn privilege_expr(p: AccessPrivilege) -> &'static str {
    match p {
        AccessPrivilege::View => "AccessPrivilege::View",
        AccessPrivilege::Operate => "AccessPrivilege::Operate",
        AccessPrivilege::Manage => "AccessPrivilege::Manage",
        AccessPrivilege::Administer => "AccessPrivilege::Administer",
    }
}

fn opt_privilege_expr(p: Option<AccessPrivilege>) -> Tokens {
    if let Some(priv_level) = p {
        quote!(Some($(privilege_expr(priv_level))))
    } else {
        quote!(None)
    }
}

fn attribute_references_fabric_scoped_struct(
    attr: &AttributeDef,
    cluster_structs: &[StructDef],
    global_defs: &GlobalDefs,
    all_structs: &BTreeMap<String, StructDef>,
) -> bool {
    let target = if attr.is_array {
        attr.entry_type.as_deref().unwrap_or(&attr.type_str)
    } else {
        attr.type_str.as_str()
    };
    let clean = target.strip_suffix("Struct").unwrap_or(target);
    let matches_name = |st: &StructDef| st.name.eq_ignore_ascii_case(target) || st.name.eq_ignore_ascii_case(clean);
    let resolved = cluster_structs
        .iter()
        .find(|st| matches_name(st))
        .or_else(|| global_defs.structs.iter().find(|st| matches_name(st)))
        .or_else(|| all_structs.values().find(|st| matches_name(st)));
    resolved.is_some_and(|st| st.is_fabric_scoped)
}

fn render_cluster_descriptor(
    c: &ClusterDef,
    global_defs: &GlobalDefs,
    all_enums: &BTreeMap<String, EnumDef>,
    all_bitmaps: &BTreeMap<String, BitmapDef>,
    all_structs: &BTreeMap<String, StructDef>,
) -> Result<Tokens, Error> {
    let ctx = TypeContext::new(
        &c.attributes,
        &c.enums,
        &c.bitmaps,
        &c.structs,
        global_defs,
        all_enums,
        all_bitmaps,
        all_structs,
    );
    let mut visiting = BTreeSet::new();
    let cluster_cfg = format!("cluster_{}", to_snake_case(&c.name));
    let cid_hex = format_hex(u64::from(c.code), 4);

    let choice_tokens: Vec<Tokens> = c
        .choices
        .iter()
        .filter_map(|ch| {
            let member_ids: Vec<Tokens> = ch
                .members
                .iter()
                .filter_map(|m| {
                    c.attributes
                        .iter()
                        .find(|a| a.name == *m)
                        .map(|a| quote!($(format_hex(u64::from(a.code), 4))))
                })
                .collect();
            if member_ids.is_empty() {
                return None;
            }
            let min_u8 = u8::try_from(ch.min.unwrap_or(1)).unwrap_or(1);
            let max_u8 = u8::try_from(ch.max.unwrap_or(1)).unwrap_or(1);
            let more_str = if ch.more { "true" } else { "false" };
            Some(quote! {
                ChoiceGroup {
                    min: $min_u8,
                    max: $max_u8,
                    more: $more_str,
                    members: &[$(for id in &member_ids join (, ) => $id)],
                }
            })
        })
        .collect();

    let mut event_tokens = Vec::with_capacity(c.events.len());
    for ev in &c.events {
        let ev_prio = event_priority_expr(&ev.name, &ev.priority)?;
        let mut ev_fields = Vec::with_capacity(ev.fields.len());
        for f in &ev.fields {
            ev_fields.push(field_descriptor_tokens(f, &ctx, Some(c), &mut visiting)?);
        }
        let ev_ctx = format!("{}::{}", c.name, ev.name);
        let ev_conf = compile_conformance_slice(&ev.conformance, false, Some(c), &ev_ctx)?;
        let ev_read_priv = privilege_expr(ev.access.read_privilege.unwrap_or(AccessPrivilege::View));
        event_tokens.push(quote! {
            EventDescriptor {
                id: EventId::new($(format_hex(u64::from(ev.code), 2))),
                name: $(quoted(&ev.name)),
                priority: $ev_prio,
                access: $(access_flags_expr(&ev.access)),
                read_privilege: $ev_read_priv,
                fields: &[
                    $(for f_tok in &ev_fields join ($['\r']) =>
                        $f_tok,
                    )
                ],
                conformance: $ev_conf,
            },
        });
    }

    let mut attr_tokens = Vec::with_capacity(c.attributes.len());
    for a in &c.attributes {
        let constraint = value_constraint_tokens(
            &a.type_str,
            a.entry_type.as_deref(),
            a.is_array,
            a.is_nullable,
            a.min.as_deref(),
            a.max.as_deref(),
            a.min_length,
            a.length,
            &ctx,
            &mut visiting,
        )?;
        let attr_ctx = format!("{}::{}", c.name, a.name);
        let conf = compile_conformance_slice(&a.conformance, a.is_optional, Some(c), &attr_ctx)?;
        let mut effective_access = a.access;
        if attribute_references_fabric_scoped_struct(a, &c.structs, global_defs, all_structs) {
            effective_access.fabric_scoped = true;
        }
        let read_priv = opt_privilege_expr(
            effective_access
                .read
                .then(|| effective_access.read_privilege.unwrap_or(AccessPrivilege::View)),
        );
        let write_priv = opt_privilege_expr(
            effective_access
                .write
                .then(|| effective_access.write_privilege.unwrap_or(AccessPrivilege::Operate)),
        );
        attr_tokens.push(quote! {
            AttributeDescriptor {
                id: AttributeId::new($(format_hex(u64::from(a.code), 4))),
                name: $(quoted(&a.name)),
                field_name: $(quoted(to_rust_field_name(&a.name))),
                access: $(access_flags_expr(&effective_access)),
                quality: $(quality_flags_expr(a.quality)),
                read_privilege: $read_priv,
                write_privilege: $write_priv,
                constraint: $constraint,
                conformance: $conf,
            },
        });
    }

    let cmd_tokens = render_command_descriptors(c, &ctx, &mut visiting)?;

    let cluster_rev = c.cluster_revision;
    Ok(quote! {
        #[cfg($(cluster_cfg.as_str()))]
        ClusterDescriptor {
            id: ClusterId::new($cid_hex),
            revision: $cluster_rev,
            name: $(quoted(&c.name)),
            attributes: &[
                $(for a_tok in &attr_tokens join ($['\r']) => $a_tok)
            ],
            commands: &[
                $(for cmd_tok in &cmd_tokens join ($['\r']) => $cmd_tok)
            ],
            events: &[
                $(for ev_tok in &event_tokens join ($['\r']) => $ev_tok)
            ],
            choice_groups: &[
                $(for cg in &choice_tokens join ($['\r']) => $cg,)
            ],
        },
    })
}

fn render_command_descriptors(
    c: &ClusterDef,
    ctx: &TypeContext<'_>,
    visiting: &mut BTreeSet<String>,
) -> Result<Vec<Tokens>, Error> {
    let mut cmd_tokens = Vec::with_capacity(c.commands.len());
    for cmd in &c.commands {
        let mut cmd_fields = Vec::with_capacity(cmd.args.len());
        for f in &cmd.args {
            cmd_fields.push(field_descriptor_tokens(f, ctx, Some(c), visiting)?);
        }
        let cmd_ctx = format!("{}::{}", c.name, cmd.name);
        let conf = compile_conformance_slice(&cmd.conformance, false, Some(c), &cmd_ctx)?;
        let invoke_priv = opt_privilege_expr(
            (cmd.direction == CommandDirection::ClientToServer)
                .then(|| cmd.access.invoke_privilege.unwrap_or(AccessPrivilege::Operate)),
        );
        let response_id = if cmd.direction == CommandDirection::ClientToServer {
            cmd.response
                .as_deref()
                .and_then(|resp_name| {
                    c.commands.iter().find(|cand| {
                        cand.direction == CommandDirection::ServerToClient && cand.name.eq_ignore_ascii_case(resp_name)
                    })
                })
                .map_or_else(
                    || quote!(None),
                    |resp| quote!(Some(CommandId::new($(format_hex(u64::from(resp.code), 2))))),
                )
        } else {
            quote!(None)
        };
        cmd_tokens.push(quote! {
            CommandDescriptor {
                id: CommandId::new($(format_hex(u64::from(cmd.code), 2))),
                name: $(quoted(&cmd.name)),
                direction: $(command_direction_expr(cmd.direction)),
                access: $(access_flags_expr(&cmd.access)),
                quality: $(quality_flags_expr(cmd.quality)),
                invoke_privilege: $invoke_priv,
                response_id: $response_id,
                fields: &[
                    $(for f_tok in &cmd_fields join ($['\r']) =>
                        $f_tok,
                    )
                ],
                conformance: $conf,
            },
        });
    }
    Ok(cmd_tokens)
}

fn render_device_type_descriptor(
    version: &str,
    d: &ParsedDeviceType,
    cluster_by_name: &BTreeMap<&str, &ClusterDef>,
) -> Result<Tokens, Error> {
    let ep_feat = format!("endpoint-{}", to_kebab_case(&d.name));
    let did_hex = format_hex(u64::from(d.device_id), 4);

    let mut server_reqs: Vec<Tokens> = Vec::new();
    for cname in &d.mandatory_server_clusters {
        if let Some(c) = cluster_by_name.get(cname.as_str()) {
            let cid = format_hex(u64::from(c.code), 4);
            server_reqs.push(
                quote!(DeviceClusterReq { cluster_id: ClusterId::new($cid), conformance: &[ConformanceOp::Mandatory] }),
            );
        }
    }
    for cname in &d.optional_server_clusters {
        if let Some(c) = cluster_by_name.get(cname.as_str()) {
            let cid = format_hex(u64::from(c.code), 4);
            server_reqs.push(
                quote!(DeviceClusterReq { cluster_id: ClusterId::new($cid), conformance: &[ConformanceOp::Optional] }),
            );
        }
    }
    for cname in &d.disallowed_clusters {
        if let Some(c) = cluster_by_name.get(cname.as_str()) {
            let cid = format_hex(u64::from(c.code), 4);
            server_reqs.push(
                quote!(DeviceClusterReq { cluster_id: ClusterId::new($cid), conformance: &[ConformanceOp::Disallow] }),
            );
        }
    }

    let mut client_reqs: Vec<Tokens> = Vec::new();
    for cname in &d.mandatory_client_clusters {
        if let Some(c) = cluster_by_name.get(cname.as_str()) {
            let cid = format_hex(u64::from(c.code), 4);
            client_reqs.push(
                quote!(DeviceClusterReq { cluster_id: ClusterId::new($cid), conformance: &[ConformanceOp::Mandatory] }),
            );
        }
    }
    for cname in &d.optional_client_clusters {
        if let Some(c) = cluster_by_name.get(cname.as_str()) {
            let cid = format_hex(u64::from(c.code), 4);
            client_reqs.push(
                quote!(DeviceClusterReq { cluster_id: ClusterId::new($cid), conformance: &[ConformanceOp::Optional] }),
            );
        }
    }

    let mut include_tokens: Vec<Tokens> = Vec::new();
    for inc in &d.includes {
        let Some(c) = cluster_by_name.get(inc.cluster.as_str()) else {
            continue;
        };
        let attr_cands: Vec<(Option<&str>, &str)> = c
            .attributes
            .iter()
            .map(|a| (a.define.as_deref(), a.name.as_str()))
            .collect();
        let mut req_attrs = Vec::new();
        for t in &inc.required_attributes {
            let Some(attr) = resolve_include_target(t, &attr_cands, to_shouty_snake_case)
                .and_then(|name| c.attributes.iter().find(|a| a.name == name))
            else {
                if !is_legacy_device_include_ignored(version, t) {
                    return Err(Error::UnresolvedDeviceTypeInclude {
                        device_type: d.name.clone(),
                        kind: "attribute".to_owned(),
                        target: t.clone(),
                    });
                }
                continue;
            };
            req_attrs.push(quote!(AttributeId::new($(format_hex(u64::from(attr.code), 4)))));
        }

        let all_cmd_cands: Vec<(Option<&str>, &str)> = c.commands.iter().map(|cm| (None, cm.name.as_str())).collect();
        let mut seen_cmd_ids = BTreeSet::new();
        let mut req_cmds = Vec::new();
        for t in &inc.required_commands {
            let Some(cmd) = resolve_include_target(t, &all_cmd_cands, to_shouty_snake_case)
                .and_then(|name| c.commands.iter().find(|cm| cm.name == name))
            else {
                if !is_legacy_device_include_ignored(version, t) {
                    return Err(Error::UnresolvedDeviceTypeInclude {
                        device_type: d.name.clone(),
                        kind: "command".to_owned(),
                        target: t.clone(),
                    });
                }
                continue;
            };
            if cmd.direction == CommandDirection::ClientToServer && seen_cmd_ids.insert(cmd.code) {
                req_cmds.push(quote!(CommandId::new($(format_hex(u64::from(cmd.code), 2)))));
            }
        }

        let ev_cands: Vec<(Option<&str>, &str)> = c.events.iter().map(|ev| (None, ev.name.as_str())).collect();
        let mut req_evs = Vec::new();
        for t in &inc.required_events {
            let Some(ev) = resolve_include_target(t, &ev_cands, to_shouty_snake_case)
                .and_then(|name| c.events.iter().find(|ev| ev.name == name))
            else {
                if !is_legacy_device_include_ignored(version, t) {
                    return Err(Error::UnresolvedDeviceTypeInclude {
                        device_type: d.name.clone(),
                        kind: "event".to_owned(),
                        target: t.clone(),
                    });
                }
                continue;
            };
            req_evs.push(quote!(EventId::new($(format_hex(u64::from(ev.code), 2)))));
        }

        if req_attrs.is_empty() && req_cmds.is_empty() && req_evs.is_empty() {
            continue;
        }
        let cid = format_hex(u64::from(c.code), 4);
        let is_srv = if inc.is_server { "true" } else { "false" };
        include_tokens.push(quote! {
            DeviceTypeIncludeItem {
                cluster_id: ClusterId::new($cid),
                is_server: $is_srv,
                required_attributes: &[$(for a in &req_attrs join (, ) => $a)],
                required_commands: &[$(for cm in &req_cmds join (, ) => $cm)],
                required_events: &[$(for ev in &req_evs join (, ) => $ev)],
            }
        });
    }

    Ok(quote! {
        #[cfg(feature = $(quoted(&ep_feat)))]
        DeviceTypeDescriptor {
            id: DeviceTypeId::new($did_hex),
            name: $(quoted(&d.name)),
            server_clusters: &[$(for r in &server_reqs join ($['\r']) => $r,)],
            client_clusters: &[$(for r in &client_reqs join ($['\r']) => $r,)],
            choice_groups: &[],
            includes: &[$(for inc in &include_tokens join ($['\r']) => $inc,)],
        },
    })
}
