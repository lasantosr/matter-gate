use std::collections::BTreeSet;

use genco::{quote, tokens::quoted};

use super::context::{
    PushLine as _, Tokens, format_hex, resolve_cluster_id_expr, to_rust_field_name, with_method_name,
};
use crate::model::{ClusterDef, ParsedDeviceType, sanitize_identifier, to_snake_case};

/// Matter device type id of the `RootNode` device type.
const ROOT_NODE_DEVICE_TYPE_ID: u32 = 0x0016;

pub(crate) fn generate_single_device_type_tokens(
    device_type: &ParsedDeviceType,
    available_clusters: &[&str],
    cluster_defs: &[ClusterDef],
    eq_clusters: &BTreeSet<String>,
    version: &str,
) -> Tokens {
    let mut out = Tokens::new();

    let header =
        format!("// AUTO-GENERATED BY cargo xtask codegen-spec (Matter Spec: {version}) - DO NOT EDIT MANUALLY");
    let intro = format!(
        "//! Standard Matter {} Device Type and compile-time conformance models.",
        device_type.type_name
    );

    let referenced_clusters = collect_referenced_clusters(&[device_type], available_clusters);
    let resolved = resolve_device_type_clusters(device_type, available_clusters, cluster_defs);
    let has_optional = !resolved.optional_fields.is_empty();
    let v_mod = format!("v{}", version.replace('.', "_"));

    let header_tokens: Tokens = quote! {
        $header
        $intro

        $(if resolved.optional_fields.is_empty() =>
            use alloc::vec;
        )
        $(if !resolved.optional_fields.is_empty() =>
            use alloc::vec::Vec;
        )

        use crate::{
            model::{
                Cluster, ClusterId, DeviceTypeEntry, DeviceTypeId, Endpoint, EndpointId,
                $(if has_optional => Optional,)
            },
            error::EndpointError,
            traits::{DeviceTypeSpec, update_descriptor_cluster},
        };
        #[cfg(feature = $(quoted("serde")))]
        use serde::{Deserialize, Serialize};

        $(emit_cluster_use_statements(&referenced_clusters, &v_mod))
    };
    out.append(header_tokens);
    out.push_blank();

    emit_single_device_type(&mut out, device_type, available_clusters, cluster_defs, eq_clusters);

    out
}

pub(crate) fn is_device_type_empty(
    device_type: &ParsedDeviceType,
    available_clusters: &[&str],
    cluster_defs: &[ClusterDef],
) -> bool {
    let resolved = resolve_device_type_clusters(device_type, available_clusters, cluster_defs);
    resolved.mandatory_fields.is_empty() && resolved.optional_fields.is_empty()
}

pub(super) fn emit_single_device_type(
    out: &mut Tokens,
    device_type: &ParsedDeviceType,
    available_clusters: &[&str],
    cluster_defs: &[ClusterDef],
    eq_clusters: &BTreeSet<String>,
) {
    let ParsedDeviceType {
        name: struct_name,
        type_name,
        device_id,
        revision,
        domain,
        class,
        scope,
        superset,
        ..
    } = device_type;

    let superset_doc = superset
        .as_deref()
        .map_or(String::new(), |superset_name| format!(" (Superset: {superset_name})"));
    let doc = format!("/// {type_name} (Class: {class}, Scope: {scope}, Domain: {domain}{superset_doc}).");

    let dt_id_hex = format_hex(u64::from(*device_id), 4);
    let class_expr = some_str_or_none(class);
    let scope_expr = some_str_or_none(scope);
    let superset_expr: Tokens = if let Some(superset_name) = superset {
        quote!(Some($(quoted(superset_name))))
    } else {
        quote!(None)
    };

    let resolved = resolve_device_type_clusters(device_type, available_clusters, cluster_defs);
    let has_both = !resolved.mandatory_fields.is_empty() && !resolved.optional_fields.is_empty();
    let all_mandatory = !resolved.mandatory_fields.is_empty() && resolved.optional_fields.is_empty();
    let all_optional = resolved.mandatory_fields.is_empty() && !resolved.optional_fields.is_empty();

    let can_derive_eq_hash = can_derive_eq_hash(&resolved, eq_clusters);
    let derives = if can_derive_eq_hash {
        "Debug, Clone, PartialEq, Eq, Hash, Default"
    } else {
        "Debug, Clone, PartialEq, Default"
    };

    let struct_def_tokens = emit_device_type_main_struct(
        struct_name,
        &doc,
        has_both,
        all_mandatory,
        all_optional,
        &resolved.mandatory_fields,
        &resolved.optional_fields,
        derives,
    );

    let methods_tokens = emit_device_type_methods(
        has_both,
        all_mandatory,
        all_optional,
        &resolved.mandatory_fields,
        &resolved.optional_fields,
    );

    let constants = emit_device_type_constants(
        struct_name,
        &dt_id_hex,
        *revision,
        &class_expr,
        &scope_expr,
        &superset_expr,
        &resolved,
    );

    let is_root_node = *device_id == ROOT_NODE_DEVICE_TYPE_ID;
    let wire_conversions = emit_endpoint_wire_conversions(struct_name, &resolved, is_root_node);
    let is_empty = resolved.mandatory_fields.is_empty() && resolved.optional_fields.is_empty();
    let is_empty_str = if is_empty { "true" } else { "false" };
    let view_name = format!("{struct_name}View");

    let spec_and_dispatch = emit_device_type_spec_and_dispatch(struct_name, &view_name, is_empty_str, &resolved);

    out.append(quote! {
        $struct_def_tokens

        impl $struct_name {
            $constants
            $methods_tokens
        }

        $(if let [(_, ctype)] = resolved.mandatory_fields.as_slice() =>
            impl From<$ctype> for $struct_name {
                #[inline]
                fn from(val: $ctype) -> Self {
                    Self::new(val)
                }
            }
        )
        $wire_conversions
        $spec_and_dispatch
    });
    out.push_blank();
}

/// Whether every cluster field of the device type derives `Eq` and `Hash`.
fn can_derive_eq_hash(resolved: &ResolvedDeviceTypeClusters, eq_clusters: &BTreeSet<String>) -> bool {
    resolved
        .mandatory_fields
        .iter()
        .chain(&resolved.optional_fields)
        .all(|(_, ctype)| eq_clusters.contains(ctype.strip_suffix("Cluster").unwrap_or(ctype)))
}

/// Emits `Some("value")`, or `None` for an empty string.
fn some_str_or_none(value: &str) -> Tokens {
    if value.is_empty() {
        quote!(None)
    } else {
        quote!(Some($(quoted(value))))
    }
}

fn collect_referenced_clusters(device_types: &[&ParsedDeviceType], available_clusters: &[&str]) -> BTreeSet<String> {
    let mut referenced = BTreeSet::new();
    for device_type in device_types {
        let all_clusters = device_type
            .mandatory_server_clusters
            .iter()
            .chain(&device_type.optional_server_clusters)
            .chain(&device_type.mandatory_client_clusters)
            .chain(&device_type.optional_client_clusters);
        for cluster in all_clusters {
            let clean = sanitize_identifier(cluster);
            if available_clusters.iter().any(|name| *name == clean) {
                referenced.insert(clean);
            }
        }
    }
    referenced
}

fn emit_cluster_use_statements(referenced_clusters: &BTreeSet<String>, v_mod: &str) -> Tokens {
    let mut tokens = Tokens::new();
    let mut used_aliases = BTreeSet::new();
    for cluster_name in referenced_clusters {
        let snake = to_snake_case(cluster_name);
        if snake.len().saturating_add(cluster_name.len()) > 80 {
            let prefix: String = snake.chars().take(8).collect();
            let base_alias = format!("c_{prefix}");
            let mut alias = base_alias.clone();
            let mut suffix = 2_usize;
            while !used_aliases.insert(alias.clone()) {
                alias = format!("{base_alias}_{suffix}");
                suffix = suffix.saturating_add(1);
            }
            tokens.append(quote! {
                use crate::$v_mod::clusters::$(&snake) as $(&alias);
                use $(&alias)::$(cluster_name.as_str())Cluster;
            });
        } else {
            tokens.append(quote! {
                use crate::$v_mod::clusters::$(&snake)::$(cluster_name.as_str())Cluster;
            });
        }
    }
    tokens
}

struct ResolvedDeviceTypeClusters {
    mandatory_server: Vec<String>,
    optional_server: Vec<String>,
    mandatory_client: Vec<String>,
    optional_client: Vec<String>,
    disallowed: Vec<String>,
    mandatory_fields: Vec<(String, String)>,
    optional_fields: Vec<(String, String)>,
}

fn resolve_device_type_clusters(
    device_type: &ParsedDeviceType,
    available_clusters: &[&str],
    cluster_defs: &[ClusterDef],
) -> ResolvedDeviceTypeClusters {
    let mandatory_server = device_type
        .mandatory_server_clusters
        .iter()
        .filter_map(|cluster| resolve_cluster_id_expr(cluster, available_clusters, cluster_defs))
        .collect();
    let optional_server = device_type
        .optional_server_clusters
        .iter()
        .filter_map(|cluster| resolve_cluster_id_expr(cluster, available_clusters, cluster_defs))
        .collect();
    let mandatory_client = device_type
        .mandatory_client_clusters
        .iter()
        .filter_map(|cluster| resolve_cluster_id_expr(cluster, available_clusters, cluster_defs))
        .collect();
    let optional_client = device_type
        .optional_client_clusters
        .iter()
        .filter_map(|cluster| resolve_cluster_id_expr(cluster, available_clusters, cluster_defs))
        .collect();
    let disallowed = device_type
        .disallowed_clusters
        .iter()
        .filter_map(|cluster| {
            let clean = sanitize_identifier(cluster);
            let cluster_def = cluster_defs.iter().find(|def| def.name.eq_ignore_ascii_case(&clean))?;
            let hex = format_hex(u64::from(cluster_def.code), 4);
            Some(format!("ClusterId::new({hex})"))
        })
        .collect();

    let active_mandatory: Vec<String> = device_type
        .mandatory_server_clusters
        .iter()
        .map(|cluster| sanitize_identifier(cluster))
        .filter(|clean| clean != "Descriptor" && available_clusters.iter().any(|cluster_name| *cluster_name == clean))
        .collect();

    let active_optional: Vec<String> = device_type
        .optional_server_clusters
        .iter()
        .map(|cluster| sanitize_identifier(cluster))
        .filter(|clean| clean != "Descriptor" && available_clusters.iter().any(|cluster_name| *cluster_name == clean))
        .collect();

    let mandatory_fields: Vec<(String, String)> = active_mandatory
        .iter()
        .map(|cluster| (to_rust_field_name(cluster), format!("{cluster}Cluster")))
        .collect();

    let optional_fields: Vec<(String, String)> = active_optional
        .iter()
        .map(|cluster| (to_rust_field_name(cluster), format!("{cluster}Cluster")))
        .collect();

    ResolvedDeviceTypeClusters {
        mandatory_server,
        optional_server,
        mandatory_client,
        optional_client,
        disallowed,
        mandatory_fields,
        optional_fields,
    }
}

fn emit_device_type_main_struct(
    struct_name: &str,
    doc: &str,
    has_both: bool,
    all_mandatory: bool,
    all_optional: bool,
    mandatory_fields: &[(String, String)],
    optional_fields: &[(String, String)],
    derives: &str,
) -> Tokens {
    if has_both {
        quote! {
            $doc
            #[derive($derives)]
            #[cfg_attr(feature = $(quoted("serde")), derive(Serialize, Deserialize))]
            #[cfg_attr(feature = $(quoted("schemars")), derive(schemars::JsonSchema))]
            #[cfg_attr(all(feature = $(quoted("serde")), feature = $(quoted("deny-unknown-fields"))), serde(deny_unknown_fields))]
            #[cfg_attr(all(feature = $(quoted("schemars")), feature = $(quoted("deny-unknown-fields"))), schemars(deny_unknown_fields))]
            pub struct $struct_name {
                $(for (fname, ctype) in mandatory_fields join ($['\r']) =>
                    pub $fname: $ctype,
                )
                $(for (fname, ctype) in optional_fields join ($['\r']) =>
                    #[cfg_attr(feature = $(quoted("serde")), serde(default, skip_serializing_if = $(quoted("Optional::is_omitted"))))]
                    #[cfg_attr(all(not(feature = $(quoted("serde"))), feature = $(quoted("schemars"))), schemars(default))]
                    pub $fname: Optional<$ctype>,
                )
            }
        }
    } else if all_mandatory {
        quote! {
            $doc
            #[derive($derives)]
            #[cfg_attr(feature = $(quoted("serde")), derive(Serialize, Deserialize))]
            #[cfg_attr(feature = $(quoted("schemars")), derive(schemars::JsonSchema))]
            #[cfg_attr(all(feature = $(quoted("serde")), feature = $(quoted("deny-unknown-fields"))), serde(deny_unknown_fields))]
            #[cfg_attr(all(feature = $(quoted("schemars")), feature = $(quoted("deny-unknown-fields"))), schemars(deny_unknown_fields))]
            pub struct $struct_name {
                $(for (fname, ctype) in mandatory_fields join ($['\r']) =>
                    pub $fname: $ctype,
                )
            }
        }
    } else if all_optional {
        quote! {
            $doc
            #[derive($derives)]
            #[cfg_attr(feature = $(quoted("serde")), derive(Serialize, Deserialize))]
            #[cfg_attr(feature = $(quoted("schemars")), derive(schemars::JsonSchema))]
            #[cfg_attr(all(feature = $(quoted("serde")), feature = $(quoted("deny-unknown-fields"))), serde(deny_unknown_fields))]
            #[cfg_attr(all(feature = $(quoted("schemars")), feature = $(quoted("deny-unknown-fields"))), schemars(deny_unknown_fields))]
            pub struct $struct_name {
                $(for (fname, ctype) in optional_fields join ($['\r']) =>
                    #[cfg_attr(
                        feature = $(quoted("serde")),
                        serde(default, skip_serializing_if = $(quoted("Optional::is_omitted")))
                    )]
                    #[cfg_attr(all(not(feature = $(quoted("serde"))), feature = $(quoted("schemars"))), schemars(default))]
                    pub $fname: Optional<$ctype>,
                )
            }
        }
    } else {
        quote! {
            $doc
            #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
            #[cfg_attr(feature = $(quoted("serde")), derive(Serialize, Deserialize))]
            #[cfg_attr(feature = $(quoted("schemars")), derive(schemars::JsonSchema))]
            pub struct $struct_name;
        }
    }
}

fn emit_device_type_methods(
    has_both: bool,
    all_mandatory: bool,
    all_optional: bool,
    mandatory_fields: &[(String, String)],
    optional_fields: &[(String, String)],
) -> Tokens {
    if has_both {
        quote! {
            #[must_use]
            pub fn new(
                $(for (fname, ctype) in mandatory_fields join ($['\r']) =>
                    $fname: impl Into<$ctype>,
                )
            ) -> Self {
                Self {
                    $(for (fname, _) in mandatory_fields join ($['\r']) =>
                        $fname: $fname.into(),
                    )
                    $(for (fname, _) in optional_fields join ($['\r']) =>
                        $fname: Optional::Omitted,
                    )
                }
            }

            $(for (fname, ctype) in optional_fields join ($['\n']) =>
                #[must_use]
                pub fn $(with_method_name(fname))(mut self, cluster: impl Into<$ctype>) -> Self {
                    self.$fname = Optional::Present(cluster.into());
                    self
                }
            )
        }
    } else if all_mandatory {
        quote! {
            #[must_use]
            pub fn new(
                $(for (fname, ctype) in mandatory_fields join ($['\r']) =>
                    $fname: impl Into<$ctype>,
                )
            ) -> Self {
                Self {
                    $(for (fname, _) in mandatory_fields join ($['\r']) =>
                        $fname: $fname.into(),
                    )
                }
            }
        }
    } else if all_optional {
        quote! {
            pub const NONE: Self = Self {
                $(for (fname, _) in optional_fields join ($['\r']) =>
                    $fname: Optional::Omitted,
                )
            };

            #[must_use]
            pub fn new() -> Self {
                Self::default()
            }

            $(for (fname, ctype) in optional_fields join ($['\n']) =>
                #[must_use]
                pub fn $(with_method_name(fname))(mut self, cluster: impl Into<$ctype>) -> Self {
                    self.$fname = Optional::Present(cluster.into());
                    self
                }
            )
        }
    } else {
        quote! {
            pub const NONE: Self = Self;

            #[must_use]
            pub const fn new() -> Self {
                Self
            }
        }
    }
}

fn emit_device_type_constants(
    struct_name: &str,
    dt_id_hex: &str,
    revision: u16,
    class_expr: &Tokens,
    scope_expr: &Tokens,
    superset_expr: &Tokens,
    resolved: &ResolvedDeviceTypeClusters,
) -> Tokens {
    quote! {
        pub const DEVICE_TYPE_ID: DeviceTypeId = DeviceTypeId::new($dt_id_hex);
        pub const REVISION: u16 = $revision;
        pub const NAME: &'static str = $(quoted(struct_name));
        pub const CLASS: Option<&'static str> = $class_expr;
        pub const SCOPE: Option<&'static str> = $scope_expr;
        pub const SUPERSET: Option<&'static str> = $superset_expr;

        pub const MANDATORY_SERVER_CLUSTERS: &'static [ClusterId] = &[
            $(for cluster_expr in &resolved.mandatory_server join ($['\r']) => $cluster_expr,)
        ];
        pub const OPTIONAL_SERVER_CLUSTERS: &'static [ClusterId] = &[
            $(for cluster_expr in &resolved.optional_server join ($['\r']) => $cluster_expr,)
        ];
        pub const MANDATORY_CLIENT_CLUSTERS: &'static [ClusterId] = &[
            $(for cluster_expr in &resolved.mandatory_client join ($['\r']) => $cluster_expr,)
        ];
        pub const OPTIONAL_CLIENT_CLUSTERS: &'static [ClusterId] = &[
            $(for cluster_expr in &resolved.optional_client join ($['\r']) => $cluster_expr,)
        ];
        pub const DISALLOWED_CLUSTERS: &'static [ClusterId] = &[
            $(for cluster_expr in &resolved.disallowed join ($['\r']) => $cluster_expr,)
        ];
    }
}

fn emit_endpoint_wire_conversions(
    struct_name: &str,
    resolved: &ResolvedDeviceTypeClusters,
    is_root_node: bool,
) -> Tokens {
    let all_fields: Vec<(&str, &str)> = resolved
        .mandatory_fields
        .iter()
        .chain(&resolved.optional_fields)
        .map(|(fname, ctype)| (fname.as_str(), ctype.as_str()))
        .collect();
    let has_server_clusters = !all_fields.is_empty();

    let from_device = quote! {
        impl $struct_name {
            /// Places this typed device on the endpoint with the given `id`.
            #[must_use]
            pub fn into_endpoint(self, id: EndpointId) -> Endpoint {
                $(if resolved.optional_fields.is_empty() =>
                    let mut clusters = vec![
                        Cluster::empty(ClusterId::DESCRIPTOR),
                        $(for (fname, _) in &resolved.mandatory_fields join ($['\r']) =>
                            Cluster::from(self.$fname),
                        )
                    ];
                )
                $(if !resolved.optional_fields.is_empty() =>
                    let mut clusters = Vec::with_capacity(
                        $(resolved.mandatory_fields.len().saturating_add(1))
                        $(for (fname, _) in &resolved.optional_fields => + usize::from(self.$fname.is_present()))
                    );
                    clusters.push(Cluster::empty(ClusterId::DESCRIPTOR));
                    $(for (fname, _) in &resolved.mandatory_fields join ($['\r']) =>
                        clusters.push(Cluster::from(self.$fname));
                    )
                    $(for (fname, _) in &resolved.optional_fields join ($['\r']) =>
                        if let Optional::Present(cluster) = self.$fname {
                            clusters.push(Cluster::from(cluster));
                        }
                    )
                )

                let descriptor = update_descriptor_cluster(
                    None,
                    &[DeviceTypeEntry::new($struct_name::DEVICE_TYPE_ID, $struct_name::REVISION)],
                    clusters.get(1..).unwrap_or_default(),
                    $struct_name::MANDATORY_CLIENT_CLUSTERS,
                );
                if let Some(slot) = clusters.first_mut() {
                    *slot = descriptor;
                }

                Endpoint::new(id, clusters)
            }
        }

        $(if is_root_node =>
            impl From<$struct_name> for Endpoint {
                fn from(device: $struct_name) -> Self {
                    device.into_endpoint(EndpointId::ROOT)
                }
            }
        )
    };

    let try_from_endpoint = quote! {
        impl TryFrom<Endpoint> for $struct_name {
            type Error = EndpointError;

            fn try_from(endpoint: Endpoint) -> Result<Self, Self::Error> {
                let _view: <Self as DeviceTypeSpec>::View<'_> = <Self as DeviceTypeSpec>::view(&endpoint)?;

                $(for (fname, ctype) in &resolved.mandatory_fields join ($['\r']) =>
                    let mut $fname: Option<$ctype> = None;
                )
                $(for (fname, ctype) in &resolved.optional_fields join ($['\r']) =>
                    let mut $fname: Option<$ctype> = None;
                )

                $(if has_server_clusters =>
                    let decode = |id, source| EndpointError::InvalidCluster { id, source };
                    for cluster in endpoint.clusters {
                        $(if let &[(fname, ctype)] = all_fields.as_slice() =>
                            if cluster.id == $ctype::CLUSTER_ID {
                                if $fname.is_some() {
                                    return Err(EndpointError::DuplicateCluster($ctype::CLUSTER_ID));
                                }
                                $fname = Some(
                                    $ctype::try_from(cluster).map_err(|s| decode($ctype::CLUSTER_ID, s))?
                                );
                            }
                        )
                        $(if all_fields.len() > 1 =>
                            match cluster.id {
                                $(for &(fname, ctype) in &all_fields join ($['\r']) =>
                                    $ctype::CLUSTER_ID => {
                                        if $fname.is_some() {
                                            return Err(EndpointError::DuplicateCluster($ctype::CLUSTER_ID));
                                        }
                                        $fname = Some(
                                            $ctype::try_from(cluster).map_err(|s| decode($ctype::CLUSTER_ID, s))?
                                        );
                                    }
                                )
                                _ => {}
                            }
                        )
                    }
                )

                $(for (fname, ctype) in &resolved.mandatory_fields join ($['\r']) =>
                    let $fname = $fname.ok_or(EndpointError::MissingMandatoryServerCluster($ctype::CLUSTER_ID))?;
                )

                Ok(Self {
                    $(for (fname, _) in &resolved.mandatory_fields join ($['\r']) =>
                        $fname,
                    )
                    $(for (fname, _) in &resolved.optional_fields join ($['\r']) =>
                        $fname: Optional::from($fname),
                    )
                })
            }
        }
    };

    quote! {
        $from_device
        $try_from_endpoint
    }
}

fn emit_device_type_spec_and_dispatch(
    struct_name: &str,
    view_name: &str,
    is_empty_str: &str,
    resolved: &ResolvedDeviceTypeClusters,
) -> Tokens {
    quote! {
        $(format!("/// Zero-allocation borrowed view over an [`Endpoint`] for [`{struct_name}`]."))
        #[derive(Debug, Clone, Copy)]
        pub struct $view_name<'a> {
            endpoint: &'a Endpoint,
        }

        impl<'a> $view_name<'a> {
            /// Returns the underlying borrowed wire [`Endpoint`].
            #[inline]
            #[must_use]
            pub const fn endpoint(&self) -> &'a Endpoint {
                self.endpoint
            }

            /// Returns the endpoint's `Descriptor` (`0x001D`) wire cluster, if present.
            #[inline]
            #[must_use]
            pub fn descriptor(&self) -> Option<&'a Cluster> {
                self.endpoint.descriptor()
            }

            $(for (fname, ctype) in resolved.mandatory_fields.iter().chain(&resolved.optional_fields) join ($['\n']) =>
                #[inline]
                #[must_use]
                pub fn $fname(&self) -> Option<&'a Cluster> {
                    self.endpoint.cluster($ctype::CLUSTER_ID)
                }
            )
        }

        crate::impl_device_type_spec!($struct_name, $view_name, $is_empty_str);
    }
}
