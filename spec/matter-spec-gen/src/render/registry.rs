/// Renders `#[cfg(feature = "registry")]` static `SpecRegistry` descriptor tables
/// for a sorted slice of clusters and device types.
pub(crate) fn render_registry_tables(
    version: &str,
    clusters: &[&ClusterDef],
    device_types: &[&ParsedDeviceType],
    global_defs: &GlobalDefs,
    all_enums: &BTreeMap<String, EnumDef>,
    all_bitmaps: &BTreeMap<String, BitmapDef>,
    all_structs: &BTreeMap<String, StructDef>,
) -> Result<String, Error> {
    let mut sorted_clusters: Vec<&ClusterDef> = clusters.to_vec();
    sorted_clusters.sort_by_key(|c| c.code);

    let mut sorted_devices: Vec<&ParsedDeviceType> = device_types.to_vec();
    sorted_devices.sort_by_key(|d| d.device_id);

    let cluster_by_name: BTreeMap<&str, &ClusterDef> = clusters.iter().map(|c| (c.name.as_str(), *c)).collect();
    let expects_event_list = global_defs.has_event_list
        || global_defs
            .attributes
            .iter()
            .any(|attr| attr.name.eq_ignore_ascii_case("EventList") || attr.code == 0xFFFA);
    let expects_event_list_str = if expects_event_list { "true" } else { "false" };

    let mut cluster_descs = Vec::with_capacity(sorted_clusters.len());
    for c in &sorted_clusters {
        cluster_descs.push(render_cluster_descriptor(
            c,
            global_defs,
            all_enums,
            all_bitmaps,
            all_structs,
        )?);
    }

    let tokens = quote! {
        $(format!("// AUTO-GENERATED BY cargo xtask codegen-spec (Matter Spec: {version}) - DO NOT EDIT MANUALLY"))
        $("//! Static read-only validation registry for Matter clusters, endpoints, and nodes.")

        #[allow(unused_imports, reason = "Generated registry imports")]
        use crate::{
            model::{
                AttributeId, ClusterId, CommandDirection, CommandId, DeviceTypeId, EventId, EventPriority, FieldId,
            },
            validate::{
                AccessFlags, AttributeDescriptor, ChoiceGroup, ClusterDescriptor, CommandDescriptor, ConformanceOp,
                DeviceClusterReq, DeviceTypeDescriptor, DeviceTypeIncludeItem, EventDescriptor, FieldDescriptor,
                ListLength, RegistryValidator, SpecRegistry, StructDescriptor, ValueBounds, ValueConstraint, ValueType,
            },
        };

        /// Static cluster descriptors sorted by [`ClusterId`].
        #[rustfmt::skip]
        static CLUSTERS: &[ClusterDescriptor] = &[
            $(for desc in &cluster_descs join ($['\r']) => $desc)
        ];

        /// Static device type descriptors sorted by [`DeviceTypeId`].
        #[rustfmt::skip]
        static DEVICE_TYPES: &[DeviceTypeDescriptor] = &[
            $(for d in &sorted_devices join ($['\r']) =>
                $(render_device_type_descriptor(d, &cluster_by_name))
            )
        ];

        /// Read-only static schema registry for this Matter specification release.
        pub static SPEC_REGISTRY: SpecRegistry = SpecRegistry {
            expects_event_list: $expects_event_list_str,
            clusters: CLUSTERS,
            device_types: DEVICE_TYPES,
        };

        /// Versioned validator bound to [`SPEC_REGISTRY`].
        pub struct Validator;

        impl Validator {
            /// Returns a [`RegistryValidator`] configured for [`ValidationMode::FullSnapshot`](crate::validate::ValidationMode::FullSnapshot)
            /// (`enforce_provisional: false`) against [`SPEC_REGISTRY`].
            #[must_use]
            #[inline]
            pub const fn full() -> RegistryValidator<'static> {
                RegistryValidator::full(&SPEC_REGISTRY)
            }

            /// Returns a [`RegistryValidator`] configured for [`ValidationMode::Partial`](crate::validate::ValidationMode::Partial)
            /// against [`SPEC_REGISTRY`].
            #[must_use]
            #[inline]
            pub const fn partial() -> RegistryValidator<'static> {
                RegistryValidator::partial(&SPEC_REGISTRY)
            }
        }
    };

    render(tokens)
}

fn command_direction_expr(dir: CommandDirection) -> &'static str {
    match dir {
        CommandDirection::ClientToServer => "CommandDirection::ClientToServer",
        CommandDirection::ServerToClient => "CommandDirection::ServerToClient",
    }
}

fn event_priority_expr(event_name: &str, priority: &str) -> Result<Tokens, Error> {
    match priority.to_ascii_lowercase().as_str() {
        "critical" => Ok(quote!(EventPriority::Critical)),
        "info" => Ok(quote!(EventPriority::Info)),
        "debug" => Ok(quote!(EventPriority::Debug)),
        other => Err(Error::UnknownEventPriority {
            event: event_name.to_owned(),
            priority: other.to_owned(),
        }),
    }
}

fn access_flags_expr(a: &AccessFlags) -> Tokens {
    let mut bits: u8 = 0;
    if a.read {
        bits |= 1 << 0;
    }
    if a.write {
        bits |= 1 << 1;
    }
    if a.fabric_scoped {
        bits |= 1 << 2;
    }
    if a.fabric_sensitive {
        bits |= 1 << 3;
    }
    if a.timed {
        bits |= 1 << 4;
    }
    quote!(AccessFlags($bits))
}

fn compile_conformance_slice(ops: &[ConformanceOp], is_optional: bool, cluster: Option<&ClusterDef>) -> Tokens {
    if ops.is_empty() {
        return if is_optional {
            quote!(&[ConformanceOp::Optional])
        } else {
            quote!(&[ConformanceOp::Mandatory])
        };
    }

    let mut emitted: Vec<Tokens> = Vec::new();
    for op in ops {
        match op {
            ConformanceOp::Mandatory => emitted.push(quote!(ConformanceOp::Mandatory)),
            ConformanceOp::Optional => emitted.push(quote!(ConformanceOp::Optional)),
            ConformanceOp::Disallow => emitted.push(quote!(ConformanceOp::Disallow)),
            ConformanceOp::Provisional => emitted.push(quote!(ConformanceOp::Provisional)),
            ConformanceOp::Deprecated => emitted.push(quote!(ConformanceOp::Deprecate)),
            ConformanceOp::Otherwise => emitted.push(quote!(ConformanceOp::Otherwise)),
            ConformanceOp::Not => emitted.push(quote!(ConformanceOp::Not)),
            ConformanceOp::Greater => emitted.push(quote!(ConformanceOp::Greater)),
            ConformanceOp::GreaterOrEqual => emitted.push(quote!(ConformanceOp::GreaterOrEqual)),
            ConformanceOp::And(n) => {
                for _ in 1..*n {
                    emitted.push(quote!(ConformanceOp::And));
                }
            }
            ConformanceOp::Or(n) => {
                for _ in 1..*n {
                    emitted.push(quote!(ConformanceOp::Or));
                }
            }
            ConformanceOp::Feature(code) => {
                let mask = cluster
                    .and_then(|c| c.features.iter().find(|f| f.code == *code || f.name == *code))
                    .map_or(0_u32, |f| 1_u32.checked_shl(f.bit).unwrap_or(0));
                let mask_hex = format_hex(u64::from(mask), 2);
                emitted.push(quote!(ConformanceOp::PushFeature($mask_hex)));
            }
            ConformanceOp::Attribute(attr_name) => {
                if attr_name.eq_ignore_ascii_case("ClusterRevision") {
                    emitted.push(quote!(ConformanceOp::PushAttrValue(0xFFFD)));
                } else if let Some(attr) = cluster.and_then(|c| {
                    c.attributes
                        .iter()
                        .find(|a| a.name == *attr_name || a.define.as_deref() == Some(attr_name.as_str()))
                }) {
                    let code_hex = format_hex(u64::from(attr.code), 4);
                    emitted.push(quote!(ConformanceOp::PushAttrPresent($code_hex)));
                } else {
                    emitted.push(quote!(ConformanceOp::PushBool(false)));
                }
            }
            ConformanceOp::Condition(_) => {
                emitted.push(quote!(ConformanceOp::PushBool(false)));
            }
            ConformanceOp::Literal(lit) => {
                if let Ok(n) = lit.trim().parse::<i64>() {
                    emitted.push(quote!(ConformanceOp::PushConst($n)));
                } else {
                    emitted.push(quote!(ConformanceOp::PushConst(0)));
                }
            }
        }
    }

    quote!(&[$(for tok in &emitted join (, ) => $tok)])
}

fn value_constraint_tokens(
    type_str: &str,
    entry_type: Option<&str>,
    is_array: bool,
    is_nullable: bool,
    min: Option<&str>,
    max: Option<&str>,
    min_length: Option<u32>,
    length: Option<u32>,
    ctx: &TypeContext<'_>,
    visiting: &mut BTreeSet<String>,
) -> Tokens {
    let nullable_str = if is_nullable { "true" } else { "false" };

    if is_array || type_str.eq_ignore_ascii_case("array") {
        let item_type = entry_type.unwrap_or(type_str);
        let item_constraint = if item_type.eq_ignore_ascii_case("array") {
            quote!(ValueConstraint {
                value_type: ValueType::Any,
                bounds: ValueBounds::None,
                nullable: false
            })
        } else {
            value_constraint_tokens(item_type, None, false, false, min, max, None, None, ctx, visiting)
        };
        let min_len = usize::try_from(min_length.unwrap_or(0)).unwrap_or(0);
        let max_len = length.map_or_else(
            || quote!(usize::MAX),
            |l| quote!($(usize::try_from(l).unwrap_or(usize::MAX))),
        );
        return quote! {
            ValueConstraint {
                value_type: ValueType::List(&ListLength {
                    min: $min_len,
                    max: $max_len,
                    item_constraint: &$item_constraint,
                }),
                bounds: ValueBounds::None,
                nullable: $nullable_str,
            }
        };
    }

    let Ok(resolved) = ctx.resolve_type("", "", type_str, entry_type, false) else {
        return quote!(ValueConstraint {
            value_type: ValueType::Any,
            bounds: ValueBounds::None,
            nullable: $nullable_str
        });
    };
    match resolved {
        ResolvedType::Primitive { rust_type, .. } => {
            primitive_constraint_tokens(rust_type, min, max, min_length, length, nullable_str)
        }
        ResolvedType::IdType { rust_type, .. } => {
            let vt = match rust_type {
                "FabricIndex" => quote!(ValueType::U8),
                "EndpointId" | "GroupId" | "VendorId" => quote!(ValueType::U16),
                "NodeId" | "FabricId" | "EventNumber" => quote!(ValueType::U64),
                _ => quote!(ValueType::U32),
            };
            quote!(ValueConstraint { value_type: $vt, bounds: ValueBounds::None, nullable: $nullable_str })
        }
        ResolvedType::SemanticType { rust_type, .. } => {
            let vt = match rust_type {
                "types::HardwareAddress"
                | "types::IpAddress"
                | "types::Ipv6Prefix"
                | "types::Ipv4Address"
                | "types::Ipv6Address" => quote!(ValueType::OctetString),
                "types::Temperature"
                | "types::TemperatureDifference"
                | "types::SignedTemperature"
                | "types::AmperageMa"
                | "types::VoltageMv"
                | "types::PowerMw"
                | "types::EnergyMwh"
                | "types::EnergyMvah"
                | "types::EnergyMvarh" => quote!(ValueType::I64),
                "types::Percent" => quote!(ValueType::U8),
                "types::Percent100ths" | "types::MatterDate" => quote!(ValueType::U16),
                "types::EpochUs" => quote!(ValueType::U64),
                _ => quote!(ValueType::U32),
            };
            quote!(ValueConstraint { value_type: $vt, bounds: ValueBounds::None, nullable: $nullable_str })
        }
        ResolvedType::Enum { name, .. } => {
            let vals: Vec<u64> = ctx
                .cluster_enums
                .iter()
                .chain(ctx.global_defs.enums.iter())
                .chain(ctx.all_enums.values())
                .find(|e| e.name == name)
                .map(|e| e.items.iter().map(|(_, v)| u64::from(*v)).collect())
                .unwrap_or_default();
            quote! {
                ValueConstraint {
                    value_type: ValueType::Enum { valid_values: &[$(for &v in &vals join (, ) => $v)] },
                    bounds: ValueBounds::None,
                    nullable: $nullable_str,
                }
            }
        }
        ResolvedType::Bitmap { name, .. } => {
            let mask: u64 = ctx
                .cluster_bitmaps
                .iter()
                .chain(ctx.global_defs.bitmaps.iter())
                .chain(ctx.all_bitmaps.values())
                .find(|b| b.name == name)
                .map(|b| b.fields.iter().fold(0_u64, |acc, (_, m)| acc | *m))
                .unwrap_or(u64::MAX);
            let mask_hex = format_hex(mask, 2);
            quote! {
                ValueConstraint {
                    value_type: ValueType::Bitmap { valid_mask: $mask_hex },
                    bounds: ValueBounds::None,
                    nullable: $nullable_str,
                }
            }
        }
        ResolvedType::Struct { name, .. } => {
            if !visiting.insert(name.clone()) {
                return quote!(ValueConstraint {
                    value_type: ValueType::Any,
                    bounds: ValueBounds::None,
                    nullable: $nullable_str
                });
            }
            let st_opt = ctx
                .cluster_structs
                .iter()
                .chain(ctx.global_defs.structs.iter())
                .chain(ctx.all_structs.values())
                .find(|s| s.name == name);
            let fields_tok = if let Some(st) = st_opt {
                quote! {
                    &[$(for f in &st.fields join ($['\r']) =>
                        $(field_descriptor_tokens(f, ctx, None, visiting)),
                    )]
                }
            } else {
                quote!(&[])
            };
            visiting.remove(&name);
            quote! {
                ValueConstraint {
                    value_type: ValueType::Struct(&StructDescriptor {
                        name: $(quoted(&name)),
                        fields: $fields_tok,
                    }),
                    bounds: ValueBounds::None,
                    nullable: $nullable_str,
                }
            }
        }
        ResolvedType::Array { .. } => {
            quote!(ValueConstraint { value_type: ValueType::Any, bounds: ValueBounds::None, nullable: $nullable_str })
        }
    }
}

fn primitive_constraint_tokens(
    rust_type: &str,
    min: Option<&str>,
    max: Option<&str>,
    min_length: Option<u32>,
    length: Option<u32>,
    nullable_str: &str,
) -> Tokens {
    let (vt, bounds) = match rust_type {
        "bool" => (quote!(ValueType::Bool), quote!(ValueBounds::None)),
        "u8" => (quote!(ValueType::U8), unsigned_bounds(min, max, u64::from(u8::MAX))),
        "u16" => (quote!(ValueType::U16), unsigned_bounds(min, max, u64::from(u16::MAX))),
        "u32" => (quote!(ValueType::U32), unsigned_bounds(min, max, u64::from(u32::MAX))),
        "u64" => (quote!(ValueType::U64), unsigned_bounds(min, max, u64::MAX)),
        "i8" => (
            quote!(ValueType::I8),
            signed_bounds(min, max, i64::from(i8::MIN), i64::from(i8::MAX)),
        ),
        "i16" => (
            quote!(ValueType::I16),
            signed_bounds(min, max, i64::from(i16::MIN), i64::from(i16::MAX)),
        ),
        "i32" => (
            quote!(ValueType::I32),
            signed_bounds(min, max, i64::from(i32::MIN), i64::from(i32::MAX)),
        ),
        "i64" => (quote!(ValueType::I64), signed_bounds(min, max, i64::MIN, i64::MAX)),
        "f32" => (quote!(ValueType::F32), quote!(ValueBounds::None)),
        "f64" => (quote!(ValueType::F64), quote!(ValueBounds::None)),
        "String" => {
            let b = match (min_length, length) {
                (None, None) => quote!(ValueBounds::None),
                (lo, hi) => {
                    let lo_u = usize::try_from(lo.unwrap_or(0)).unwrap_or(0);
                    let hi_tok = hi.map_or_else(
                        || quote!(usize::MAX),
                        |v| quote!($(usize::try_from(v).unwrap_or(usize::MAX))),
                    );
                    quote!(ValueBounds::StringLen { min: $lo_u, max: $hi_tok })
                }
            };
            (quote!(ValueType::String), b)
        }
        "crate::Bytes" => {
            let b = match (min_length, length) {
                (None, None) => quote!(ValueBounds::None),
                (lo, hi) => {
                    let lo_u = usize::try_from(lo.unwrap_or(0)).unwrap_or(0);
                    let hi_tok = hi.map_or_else(
                        || quote!(usize::MAX),
                        |v| quote!($(usize::try_from(v).unwrap_or(usize::MAX))),
                    );
                    quote!(ValueBounds::BytesLen { min: $lo_u, max: $hi_tok })
                }
            };
            (quote!(ValueType::OctetString), b)
        }
        _ => (quote!(ValueType::Any), quote!(ValueBounds::None)),
    };
    quote!(ValueConstraint { value_type: $vt, bounds: $bounds, nullable: $nullable_str })
}

fn unsigned_bounds(min: Option<&str>, max: Option<&str>, type_max: u64) -> Tokens {
    let lo = min.and_then(parse_u64_bound).unwrap_or(0);
    let hi = max.and_then(parse_u64_bound).unwrap_or(type_max);
    if lo == 0 && hi == type_max {
        quote!(ValueBounds::None)
    } else {
        quote!(ValueBounds::Unsigned { min: $lo, max: $hi })
    }
}

fn signed_bounds(min: Option<&str>, max: Option<&str>, type_min: i64, type_max: i64) -> Tokens {
    let lo = min.and_then(parse_i64_bound).unwrap_or(type_min);
    let hi = max.and_then(parse_i64_bound).unwrap_or(type_max);
    if lo == type_min && hi == type_max {
        quote!(ValueBounds::None)
    } else {
        quote!(ValueBounds::Signed { min: $lo, max: $hi })
    }
}

fn parse_u64_bound(s: &str) -> Option<u64> {
    let t = s.trim();
    if let Some(hex) = t.strip_prefix("0x").or_else(|| t.strip_prefix("0X")) {
        u64::from_str_radix(hex, 16).ok()
    } else {
        t.parse::<u64>().ok()
    }
}

fn parse_i64_bound(s: &str) -> Option<i64> {
    let t = s.trim();
    if let Some(hex) = t.strip_prefix("0x").or_else(|| t.strip_prefix("0X")) {
        i64::from_str_radix(hex, 16).ok()
    } else {
        t.parse::<i64>().ok()
    }
}

fn field_descriptor_tokens(
    f: &FieldDef,
    ctx: &TypeContext<'_>,
    cluster: Option<&ClusterDef>,
    visiting: &mut BTreeSet<String>,
) -> Tokens {
    let fid_hex = format_hex(u64::from(f.field_id), 2);
    let fname = to_rust_field_name(&f.name);
    let constraint = value_constraint_tokens(
        &f.type_str,
        f.entry_type.as_deref(),
        f.is_array,
        f.is_nullable,
        f.min.as_deref(),
        f.max.as_deref(),
        f.min_length,
        f.length,
        ctx,
        visiting,
    );
    let conf = compile_conformance_slice(&f.conformance, f.is_optional, cluster);
    quote! {
        FieldDescriptor {
            id: FieldId::new($fid_hex),
            name: $(quoted(&fname)),
            constraint: $constraint,
            conformance: $conf,
        }
    }
}

fn render_cluster_descriptor(
    c: &ClusterDef,
    global_defs: &GlobalDefs,
    all_enums: &BTreeMap<String, EnumDef>,
    all_bitmaps: &BTreeMap<String, BitmapDef>,
    all_structs: &BTreeMap<String, StructDef>,
) -> Result<Tokens, Error> {
    let ctx = TypeContext::new(
        &c.attributes,
        &c.enums,
        &c.bitmaps,
        &c.structs,
        global_defs,
        all_enums,
        all_bitmaps,
        all_structs,
    );
    let mut visiting = BTreeSet::new();
    let cluster_cfg = format!("cluster_{}", to_snake_case(&c.name));
    let cid_hex = format_hex(u64::from(c.code), 4);

    let choice_tokens: Vec<Tokens> = c
        .choices
        .iter()
        .filter_map(|ch| {
            let member_ids: Vec<Tokens> = ch
                .members
                .iter()
                .filter_map(|m| {
                    c.attributes
                        .iter()
                        .find(|a| a.name == *m)
                        .map(|a| format_hex(u64::from(a.code), 4))
                        .or_else(|| {
                            c.commands
                                .iter()
                                .find(|cmd| cmd.name == *m)
                                .map(|cmd| format_hex(u64::from(cmd.code), 2))
                        })
                        .or_else(|| {
                            c.events
                                .iter()
                                .find(|ev| ev.name == *m)
                                .map(|ev| format_hex(u64::from(ev.code), 2))
                        })
                        .map(|hex| quote!($hex))
                })
                .collect();
            if member_ids.is_empty() {
                return None;
            }
            let min_u8 = u8::try_from(ch.min.unwrap_or(1)).unwrap_or(1);
            let max_u8 = u8::try_from(ch.max.unwrap_or(1)).unwrap_or(1);
            let more_str = if ch.more { "true" } else { "false" };
            Some(quote! {
                ChoiceGroup {
                    min: $min_u8,
                    max: $max_u8,
                    more: $more_str,
                    members: &[$(for id in &member_ids join (, ) => $id)],
                }
            })
        })
        .collect();

    let mut event_tokens = Vec::with_capacity(c.events.len());
    for ev in &c.events {
        let ev_prio = event_priority_expr(&ev.name, &ev.priority)?;
        event_tokens.push(quote! {
            EventDescriptor {
                id: EventId::new($(format_hex(u64::from(ev.code), 2))),
                name: $(quoted(&ev.name)),
                priority: $ev_prio,
                access: $(access_flags_expr(&ev.access)),
                fields: &[
                    $(for f in &ev.fields join ($['\r']) =>
                        $(field_descriptor_tokens(f, &ctx, Some(c), &mut visiting)),
                    )
                ],
                conformance: $(compile_conformance_slice(&ev.conformance, false, Some(c))),
            },
        });
    }

    Ok(quote! {
        #[cfg($(cluster_cfg.as_str()))]
        ClusterDescriptor {
            id: ClusterId::new($cid_hex),
            name: $(quoted(&c.name)),
            attributes: &[
                $(for a in &c.attributes join ($['\r']) =>
                    AttributeDescriptor {
                        id: AttributeId::new($(format_hex(u64::from(a.code), 4))),
                        name: $(quoted(&a.name)),
                        field_name: $(quoted(to_rust_field_name(&a.name))),
                        access: $(access_flags_expr(&a.access)),
                        constraint: $(value_constraint_tokens(
                            &a.type_str,
                            a.entry_type.as_deref(),
                            a.is_array,
                            a.is_nullable,
                            a.min.as_deref(),
                            a.max.as_deref(),
                            a.min_length,
                            a.length,
                            &ctx,
                            &mut visiting,
                        )),
                        conformance: $(compile_conformance_slice(&a.conformance, a.is_optional, Some(c))),
                    },
                )
            ],
            commands: &[
                $(for cmd in &c.commands join ($['\r']) =>
                    CommandDescriptor {
                        id: CommandId::new($(format_hex(u64::from(cmd.code), 2))),
                        name: $(quoted(&cmd.name)),
                        direction: $(command_direction_expr(cmd.direction)),
                        access: $(access_flags_expr(&cmd.access)),
                        fields: &[
                            $(for f in &cmd.args join ($['\r']) =>
                                $(field_descriptor_tokens(f, &ctx, Some(c), &mut visiting)),
                            )
                        ],
                        conformance: $(compile_conformance_slice(&cmd.conformance, false, Some(c))),
                    },
                )
            ],
            events: &[
                $(for ev_tok in &event_tokens join ($['\r']) => $ev_tok)
            ],
            choice_groups: &[
                $(for cg in &choice_tokens join ($['\r']) => $cg,)
            ],
        },
    })
}

fn render_device_type_descriptor(d: &ParsedDeviceType, cluster_by_name: &BTreeMap<&str, &ClusterDef>) -> Tokens {
    let ep_feat = format!("endpoint-{}", to_kebab_case(&d.name));
    let did_hex = format_hex(u64::from(d.device_id), 4);

    let mut server_reqs: Vec<Tokens> = Vec::new();
    for cname in &d.mandatory_server_clusters {
        if let Some(c) = cluster_by_name.get(cname.as_str()) {
            let cid = format_hex(u64::from(c.code), 4);
            server_reqs.push(
                quote!(DeviceClusterReq { cluster_id: ClusterId::new($cid), conformance: &[ConformanceOp::Mandatory] }),
            );
        }
    }
    for cname in &d.optional_server_clusters {
        if let Some(c) = cluster_by_name.get(cname.as_str()) {
            let cid = format_hex(u64::from(c.code), 4);
            server_reqs.push(
                quote!(DeviceClusterReq { cluster_id: ClusterId::new($cid), conformance: &[ConformanceOp::Optional] }),
            );
        }
    }
    for cname in &d.disallowed_clusters {
        if let Some(c) = cluster_by_name.get(cname.as_str()) {
            let cid = format_hex(u64::from(c.code), 4);
            server_reqs.push(
                quote!(DeviceClusterReq { cluster_id: ClusterId::new($cid), conformance: &[ConformanceOp::Disallow] }),
            );
        }
    }

    let mut client_reqs: Vec<Tokens> = Vec::new();
    for cname in &d.mandatory_client_clusters {
        if let Some(c) = cluster_by_name.get(cname.as_str()) {
            let cid = format_hex(u64::from(c.code), 4);
            client_reqs.push(
                quote!(DeviceClusterReq { cluster_id: ClusterId::new($cid), conformance: &[ConformanceOp::Mandatory] }),
            );
        }
    }
    for cname in &d.optional_client_clusters {
        if let Some(c) = cluster_by_name.get(cname.as_str()) {
            let cid = format_hex(u64::from(c.code), 4);
            client_reqs.push(
                quote!(DeviceClusterReq { cluster_id: ClusterId::new($cid), conformance: &[ConformanceOp::Optional] }),
            );
        }
    }

    let mut include_tokens: Vec<Tokens> = Vec::new();
    for inc in &d.includes {
        let Some(c) = cluster_by_name.get(inc.cluster.as_str()) else {
            continue;
        };
        let attr_cands: Vec<(Option<&str>, &str)> = c
            .attributes
            .iter()
            .map(|a| (a.define.as_deref(), a.name.as_str()))
            .collect();
        let req_attrs: Vec<Tokens> = inc
            .required_attributes
            .iter()
            .filter(|t| !is_legacy_device_include_ignored(t))
            .filter_map(|t| {
                resolve_include_target(t, &attr_cands, to_shouty_snake_case)
                    .and_then(|name| c.attributes.iter().find(|a| a.name == name))
                    .map(|a| quote!(AttributeId::new($(format_hex(u64::from(a.code), 4)))))
            })
            .collect();

        let client_cmds: Vec<&CommandDef> = c
            .commands
            .iter()
            .filter(|cm| cm.direction == CommandDirection::ClientToServer)
            .collect();
        let cmd_cands: Vec<(Option<&str>, &str)> = client_cmds.iter().map(|cm| (None, cm.name.as_str())).collect();
        let mut seen_cmd_ids = BTreeSet::new();
        let req_cmds: Vec<Tokens> = inc
            .required_commands
            .iter()
            .filter(|t| !is_legacy_device_include_ignored(t))
            .filter_map(|t| {
                resolve_include_target(t, &cmd_cands, to_shouty_snake_case)
                    .and_then(|name| client_cmds.iter().find(|cm| cm.name == name))
                    .filter(|cm| seen_cmd_ids.insert(cm.code))
                    .map(|cm| quote!(CommandId::new($(format_hex(u64::from(cm.code), 2)))))
            })
            .collect();

        let ev_cands: Vec<(Option<&str>, &str)> = c.events.iter().map(|ev| (None, ev.name.as_str())).collect();
        let req_evs: Vec<Tokens> = inc
            .required_events
            .iter()
            .filter(|t| !is_legacy_device_include_ignored(t))
            .filter_map(|t| {
                resolve_include_target(t, &ev_cands, to_shouty_snake_case)
                    .and_then(|name| c.events.iter().find(|ev| ev.name == name))
                    .map(|ev| quote!(EventId::new($(format_hex(u64::from(ev.code), 2)))))
            })
            .collect();

        if req_attrs.is_empty() && req_cmds.is_empty() && req_evs.is_empty() {
            continue;
        }
        let cid = format_hex(u64::from(c.code), 4);
        let is_srv = if inc.is_server { "true" } else { "false" };
        include_tokens.push(quote! {
            DeviceTypeIncludeItem {
                cluster_id: ClusterId::new($cid),
                is_server: $is_srv,
                required_attributes: &[$(for a in &req_attrs join (, ) => $a)],
                required_commands: &[$(for cm in &req_cmds join (, ) => $cm)],
                required_events: &[$(for ev in &req_evs join (, ) => $ev)],
            }
        });
    }

    quote! {
        #[cfg(feature = $(quoted(&ep_feat)))]
        DeviceTypeDescriptor {
            id: DeviceTypeId::new($did_hex),
            name: $(quoted(&d.name)),
            server_clusters: &[$(for r in &server_reqs join ($['\r']) => $r,)],
            client_clusters: &[$(for r in &client_reqs join ($['\r']) => $r,)],
            choice_groups: &[],
            includes: &[$(for inc in &include_tokens join ($['\r']) => $inc,)],
        },
    }
}

