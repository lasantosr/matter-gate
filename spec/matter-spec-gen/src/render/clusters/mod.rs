pub(crate) fn generate_cluster_tokens(
    cluster: &ClusterDef,
    global_defs: &GlobalDefs,
    all_enums: &BTreeMap<String, EnumDef>,
    all_bitmaps: &BTreeMap<String, BitmapDef>,
    all_structs: &BTreeMap<String, StructDef>,
    version: &str,
    family: &str,
    shared_plan: Option<&SharedPlan>,
) -> Result<Tokens> {
    let ClusterDef {
        name,
        code: _code,
        cluster_revision: _cluster_revision,
        domain: _domain,
        description,
        features,
        bitmaps: _bitmaps,
        enums: _enums,
        structs: _structs,
        attributes,
        commands: _commands,
        events: _events,
        ..
    } = cluster;
    let mut out = Tokens::new();
    let cluster_struct = format!("{name}Cluster");

    let (effective_structs, effective_enums, effective_bitmaps) =
        collect_effective_types(cluster, global_defs, all_enums, all_bitmaps, all_structs);

    let referenced_global_hashes = collect_referenced_global_hashes(
        cluster,
        global_defs,
        &effective_structs,
        &effective_enums,
        &effective_bitmaps,
    );

    let has_any_member = !cluster.attributes.is_empty() || !cluster.commands.is_empty() || !cluster.events.is_empty();

    let header = format!(
        "// AUTO-GENERATED BY cargo xtask codegen-spec (Matter Spec: {version}, Family: {family}) - DO NOT EDIT \
         MANUALLY"
    );
    let cluster_header: Tokens = quote! {
        $header
        $(inner_doc_comment(description))

        #[allow(unused_imports, reason = "Generated cluster imports")]
        use crate::{
            types,
            model::{
                self, ActionId, AttributeId, AttributeValue, Cluster, ClusterId, CommandDirection, CommandId,
                DataVersion, DeviceTypeId, EndpointId, EventId, EventNumber, EventPriority, FabricId, FabricIndex,
                FieldId, GroupId, MatterStatus, NodeId, Nullable, Optional, TransactionId, VendorId,
            },
            error::{AttributeError, ClusterError, CommandError, EventError},
        };
        #[allow(unused_imports, reason = "Generated cluster imports")]
        use alloc::{format, string::String, vec, vec::Vec};
        #[allow(unused_imports, reason = "Generated cluster imports")]
        use core::{fmt, ops};
        #[cfg(feature = $(quoted("serde")))]
        #[allow(unused_imports, reason = "Generated cluster imports")]
        use serde::{Deserialize, Serialize};
        $(if has_any_member =>
            #[cfg(all(feature = $(quoted("dispatch")), feature = $(quoted("serde"))))]
            use crate::dispatch::{
                $(if !cluster.commands.is_empty() => DescribedCommandVariant,)
                $(if !cluster.attributes.is_empty() || !cluster.events.is_empty() => DescribedVariant,)
            };
        )
        $(if !referenced_global_hashes.is_empty() =>
            $(if let Some(plan) = shared_plan =>
                mod globals {
                    $(for ghash in &referenced_global_hashes join ($['\r']) =>
                        $(if let Some(ident) = plan.global_ident(ghash) =>
                            #[allow(unused_imports, reason = "Generated cluster imports")]
                            pub(super) use crate::__shared::globals::$ident::*;
                        )
                    )
                }
            )
            $(if shared_plan.is_none() =>
                #[allow(unused_imports, reason = "Generated cluster imports")]
                use super::super::globals;
            )
        )

    };
    out.append(cluster_header);
    out.push_blank();

    emit_feature_map(&mut out, features)?;

    let all_enums_map: BTreeMap<String, EnumDef> = effective_enums
        .iter()
        .map(|enm| (enm.name.clone(), enm.clone()))
        .collect();

    let all_bitmaps_map: BTreeMap<String, BitmapDef> = effective_bitmaps
        .iter()
        .map(|bitmap| (bitmap.name.clone(), bitmap.clone()))
        .collect();

    let all_structs_map: BTreeMap<String, StructDef> = effective_structs
        .iter()
        .map(|strct| (strct.name.clone(), strct.clone()))
        .collect();

    let ctx = TypeContext::new(
        attributes,
        &effective_enums,
        &effective_bitmaps,
        &effective_structs,
        global_defs,
        &all_enums_map,
        &all_bitmaps_map,
        &all_structs_map,
    );

    emit_cluster_struct_and_attribute_enum(
        &mut out,
        cluster,
        &cluster_struct,
        &effective_enums,
        &effective_structs,
        &ctx,
    )?;

    emit_bitmaps(&mut out, &effective_bitmaps, None)?;
    emit_enums(&mut out, &effective_enums, None)?;
    emit_semantic_booleans(&mut out, cluster);
    emit_structs(&mut out, &effective_structs, false, &ctx, None)?;
    emit_attributes(&mut out, cluster, &cluster_struct, &ctx)?;
    emit_commands(&mut out, cluster, &cluster_struct, &ctx)?;
    emit_events(&mut out, cluster, &cluster_struct, &ctx)?;

    Ok(out)
}

/// Returns whether the generated `<Name>Cluster` struct derives `Eq` and `Hash`.
pub(crate) fn cluster_derives_eq_hash(
    cluster: &ClusterDef,
    global_defs: &GlobalDefs,
    all_enums: &BTreeMap<String, EnumDef>,
    all_bitmaps: &BTreeMap<String, BitmapDef>,
    all_structs: &BTreeMap<String, StructDef>,
) -> bool {
    let (effective_structs, effective_enums, effective_bitmaps) =
        collect_effective_types(cluster, global_defs, all_enums, all_bitmaps, all_structs);
    let enums_map: BTreeMap<String, EnumDef> = effective_enums
        .iter()
        .map(|enm| (enm.name.clone(), enm.clone()))
        .collect();
    let bitmaps_map: BTreeMap<String, BitmapDef> = effective_bitmaps
        .iter()
        .map(|bitmap| (bitmap.name.clone(), bitmap.clone()))
        .collect();
    let structs_map: BTreeMap<String, StructDef> = effective_structs
        .iter()
        .map(|strct| (strct.name.clone(), strct.clone()))
        .collect();
    let ctx = TypeContext::new(
        &cluster.attributes,
        &effective_enums,
        &effective_bitmaps,
        &effective_structs,
        global_defs,
        &enums_map,
        &bitmaps_map,
        &structs_map,
    );
    let Ok(resolved_attrs) = resolve_cluster_attributes(cluster, &ctx) else {
        return false;
    };
    let partition = MemberPartition::new(&resolved_attrs);
    partition.is_empty() || partition.can_derive_eq_hash(&ctx)
}

fn resolve_cluster_attributes(cluster: &ClusterDef, ctx: &TypeContext<'_>) -> Result<Vec<ResolvedMember>> {
    let mut resolved_attrs = Vec::new();
    for attr in &cluster.attributes {
        let resolved = ctx.resolve_type(
            &cluster.name,
            &attr.name,
            &attr.type_str,
            attr.entry_type.as_deref(),
            attr.is_array,
        )?;
        let is_semantic_bool = (attr.type_str.eq_ignore_ascii_case("boolean")
            || attr.type_str.eq_ignore_ascii_case("bool"))
            && is_semantic_boolean_attr(&attr.name).is_some();
        let flags = MemberFlags {
            is_optional: attr.is_optional,
            is_nullable: attr.is_nullable,
            is_array: attr.is_array,
            is_semantic_bool,
        };
        resolved_attrs.push(ResolvedMember::for_attribute(
            attr.name.clone(),
            attr.code,
            flags,
            resolved,
        ));
    }
    Ok(resolved_attrs)
}

fn enqueue_struct_field_types(
    strct: &StructDef,
    scan_type: &impl Fn(&str, &mut BTreeSet<String>),
    needed: &mut BTreeSet<String>,
) {
    for field in &strct.fields {
        scan_type(&field.type_str, needed);
        if let Some(entry_type) = &field.entry_type {
            scan_type(entry_type, needed);
        }
    }
}

fn collect_effective_types(
    cluster: &ClusterDef,
    global_defs: &GlobalDefs,
    all_enums: &BTreeMap<String, EnumDef>,
    all_bitmaps: &BTreeMap<String, BitmapDef>,
    all_structs: &BTreeMap<String, StructDef>,
) -> (Vec<StructDef>, Vec<EnumDef>, Vec<BitmapDef>) {
    let mut effective_structs = cluster.structs.clone();
    let mut effective_enums = cluster.enums.clone();
    let mut effective_bitmaps = cluster.bitmaps.clone();
    let mut needed_type_names = BTreeSet::new();

    let scan_type = |type_str: &str, needed: &mut BTreeSet<String>| {
        let clean = type_str
            .strip_suffix("Struct")
            .or_else(|| type_str.strip_suffix("Enum"))
            .or_else(|| type_str.strip_suffix("Bitmap"))
            .unwrap_or(type_str);
        needed.insert(clean.to_owned());
        needed.insert(type_str.to_owned());
    };

    for attr in &cluster.attributes {
        scan_type(&attr.type_str, &mut needed_type_names);
        if let Some(entry_type) = &attr.entry_type {
            scan_type(entry_type, &mut needed_type_names);
        }
    }
    for cmd in &cluster.commands {
        for arg in &cmd.args {
            scan_type(&arg.type_str, &mut needed_type_names);
            if let Some(entry_type) = &arg.entry_type {
                scan_type(entry_type, &mut needed_type_names);
            }
        }
    }
    for event in &cluster.events {
        for field in &event.fields {
            scan_type(&field.type_str, &mut needed_type_names);
            if let Some(entry_type) = &field.entry_type {
                scan_type(entry_type, &mut needed_type_names);
            }
        }
    }

    // Add any borrowed structs, enums, bitmaps transitively
    let mut added = true;
    while added {
        added = false;
        let current_struct_names: BTreeSet<String> = effective_structs
            .iter()
            .map(|strct| strct.name.to_lowercase())
            .collect();
        let global_struct_names: BTreeSet<String> = global_defs
            .structs
            .iter()
            .map(|strct| strct.name.to_lowercase())
            .collect();

        let current_enum_names: BTreeSet<String> = effective_enums.iter().map(|enm| enm.name.to_lowercase()).collect();
        let global_enum_names: BTreeSet<String> = global_defs.enums.iter().map(|enm| enm.name.to_lowercase()).collect();

        let current_bitmap_names: BTreeSet<String> = effective_bitmaps
            .iter()
            .map(|bitmap| bitmap.name.to_lowercase())
            .collect();
        let global_bitmap_names: BTreeSet<String> = global_defs
            .bitmaps
            .iter()
            .map(|bitmap| bitmap.name.to_lowercase())
            .collect();

        for type_name in needed_type_names.clone() {
            let lower = type_name.to_lowercase();
            // Structs
            if !current_struct_names.contains(&lower)
                && !global_struct_names.contains(&lower)
                && let Some(st) = all_structs
                    .values()
                    .find(|strct| strct.name.eq_ignore_ascii_case(&type_name))
            {
                effective_structs.push(st.clone());
                added = true;
                enqueue_struct_field_types(st, &scan_type, &mut needed_type_names);
            }
            // Enums
            let clean_enm = type_name.strip_suffix("Enum").unwrap_or(&type_name);
            if !current_enum_names.contains(&lower)
                && !global_enum_names.contains(&lower)
                && let Some(enm) = all_enums.values().find(|entry| {
                    entry.name.eq_ignore_ascii_case(&type_name) || entry.name.eq_ignore_ascii_case(clean_enm)
                })
                && !effective_enums
                    .iter()
                    .any(|entry| entry.name.eq_ignore_ascii_case(&enm.name))
            {
                effective_enums.push(enm.clone());
                added = true;
            }
            // Bitmaps
            let clean_bm = type_name.strip_suffix("Bitmap").unwrap_or(&type_name);
            if !current_bitmap_names.contains(&lower)
                && !global_bitmap_names.contains(&lower)
                && let Some(bm) = all_bitmaps.values().find(|entry| {
                    entry.name.eq_ignore_ascii_case(&type_name) || entry.name.eq_ignore_ascii_case(clean_bm)
                })
                && !effective_bitmaps
                    .iter()
                    .any(|entry| entry.name.eq_ignore_ascii_case(&bm.name))
            {
                effective_bitmaps.push(bm.clone());
                added = true;
            }
        }
    }

    (effective_structs, effective_enums, effective_bitmaps)
}

fn collect_referenced_global_hashes(
    cluster: &ClusterDef,
    global_defs: &GlobalDefs,
    effective_structs: &[StructDef],
    effective_enums: &[EnumDef],
    effective_bitmaps: &[BitmapDef],
) -> BTreeSet<String> {
    let global_hashes_lower: BTreeMap<String, String> = compute_global_hashes(global_defs)
        .into_iter()
        .map(|(k, v)| (k.to_ascii_lowercase(), v))
        .collect();
    let local_names: BTreeSet<String> = effective_structs
        .iter()
        .map(|s| s.name.to_ascii_lowercase())
        .chain(effective_enums.iter().map(|e| e.name.to_ascii_lowercase()))
        .chain(effective_bitmaps.iter().map(|b| b.name.to_ascii_lowercase()))
        .collect();
    let mut out = BTreeSet::new();
    let mut add = |ty_name: &str| {
        let key = ty_name.to_ascii_lowercase();
        if !local_names.contains(&key)
            && let Some(ghash) = global_hashes_lower.get(&key)
        {
            out.insert(ghash.clone());
        }
    };
    for a in &cluster.attributes {
        add(&a.type_str);
        if let Some(et) = a.entry_type.as_deref() {
            add(et);
        }
    }
    for s in effective_structs {
        for f in &s.fields {
            add(&f.type_str);
            if let Some(et) = f.entry_type.as_deref() {
                add(et);
            }
        }
    }
    for c in &cluster.commands {
        for f in &c.args {
            add(&f.type_str);
            if let Some(et) = f.entry_type.as_deref() {
                add(et);
            }
        }
    }
    for e in &cluster.events {
        for f in &e.fields {
            add(&f.type_str);
            if let Some(et) = f.entry_type.as_deref() {
                add(et);
            }
        }
    }
    out
}
