use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::Path,
};

use anyhow::{Context as _, Result};
use matter_spec_gen::Category;
use toml_edit::{Array, DocumentMut, Item, Table, Value};

use crate::util::write_if_changed;

pub(in super::super) fn update_spec_cargo_toml(
    cargo_toml_path: &Path,
    versions: &[(String, String, String)],
    domain_families: &[Category],
    family_to_clusters: &BTreeMap<String, BTreeSet<String>>,
    family_to_endpoints: &BTreeMap<String, BTreeSet<String>>,
    endpoint_to_clusters: &BTreeMap<String, BTreeSet<String>>,
    all_cluster_features: &BTreeSet<String>,
) -> Result<()> {
    let content =
        fs::read_to_string(cargo_toml_path).with_context(|| format!("Failed to read {}", cargo_toml_path.display()))?;

    let mut doc: DocumentMut = content
        .parse()
        .with_context(|| format!("Failed to parse {}", cargo_toml_path.display()))?;

    let mut features_table = Table::new();
    features_table.decor_mut().set_prefix(
        "\n# AUTO-GENERATED BY cargo xtask codegen-spec (xtask/src/commands/codegen_spec/layout/manifest.rs) - DO NOT \
         EDIT MANUALLY\n",
    );

    // Helper to insert an item into features_table with optional section prefix comment on the key
    let insert_feature = |table: &mut Table, key: &str, arr: Array, prefix: Option<&str>| {
        table.insert(key, Item::Value(Value::Array(arr)));
        if let Some(p) = prefix
            && let Some(mut key_mut) = table.key_mut(key)
        {
            key_mut.leaf_decor_mut().set_prefix(p);
        }
    };

    // 1. Core features
    let mut default_arr = Array::new();
    default_arr.push("std");
    insert_feature(&mut features_table, "default", default_arr, Some("# Core features\n"));

    let mut std_arr = Array::new();
    std_arr.push("matter-data-model/std");
    std_arr.push("serde?/std");
    std_arr.push("bytes/std");
    insert_feature(&mut features_table, "std", std_arr, None);

    // 2. Optional Serialization & Schema Generation
    let mut serde_arr = Array::new();
    serde_arr.push("dep:serde");
    serde_arr.push("matter-data-model/serde");
    serde_arr.push("bytes/serde");
    insert_feature(
        &mut features_table,
        "serde",
        serde_arr,
        Some("\n# Optional Serialization & Schema Generation\n"),
    );

    let mut schemars_arr = Array::new();
    schemars_arr.push("dep:schemars");
    schemars_arr.push("std");
    schemars_arr.push("registry");
    schemars_arr.push("matter-data-model/schemars");
    insert_feature(&mut features_table, "schemars", schemars_arr, None);

    let mut deny_unknown_arr = Array::new();
    deny_unknown_arr.push("matter-data-model/deny-unknown-fields");
    insert_feature(&mut features_table, "deny-unknown-fields", deny_unknown_arr, None);

    // 2b. Optional Ecosystem Type Conversions
    let mut chrono_arr = Array::new();
    chrono_arr.push("dep:chrono");
    insert_feature(
        &mut features_table,
        "chrono",
        chrono_arr,
        Some("\n# Optional Ecosystem Type Conversions\n"),
    );

    let mut time_arr = Array::new();
    time_arr.push("dep:time");
    insert_feature(&mut features_table, "time", time_arr, None);

    let mut uom_arr = Array::new();
    uom_arr.push("dep:uom");
    insert_feature(&mut features_table, "uom", uom_arr, None);

    // 3. Runtime Validation, Model Registry & Dispatch Envelopes
    insert_feature(
        &mut features_table,
        "registry",
        Array::new(),
        Some("\n# Runtime Validation, Model Registry & Dispatch Envelopes\n"),
    );
    insert_feature(&mut features_table, "dispatch", Array::new(), None);

    // 4. Matter Specification Versions
    let mut first_ver = true;
    for (_, mod_name, _feat) in versions {
        let prefix = first_ver.then(|| {
            first_ver = false;
            "\n# Matter Specification Versions\n"
        });
        insert_feature(&mut features_table, mod_name.as_str(), Array::new(), prefix);
    }

    // 5. High-Level Product Domain Families
    let mut all_arr = Array::new();
    for family in domain_families {
        if family.as_str() != "testing" {
            all_arr.push(family.as_str());
        }
    }
    insert_feature(
        &mut features_table,
        "all",
        all_arr,
        Some("\n# High-Level Product Domain Families\n"),
    );

    for family in domain_families {
        let fam_str = family.as_str();
        let mut fam_arr = Array::new();

        if let Some(endpoints) = family_to_endpoints.get(fam_str) {
            for ep_feat in endpoints {
                fam_arr.push(ep_feat.as_str());
            }
        }
        if let Some(clusters) = family_to_clusters.get(fam_str) {
            for cl_feat in clusters {
                fam_arr.push(cl_feat.as_str());
            }
        }

        insert_feature(&mut features_table, fam_str, fam_arr, None);
    }

    // 6. Granular Device Endpoints (autowires required clusters)
    let mut first_ep = true;
    for (ep_feat, clusters) in endpoint_to_clusters {
        let prefix = first_ep.then(|| {
            first_ep = false;
            "\n# Granular Device Endpoints (autowires required clusters)\n"
        });
        let mut ep_deps_arr = Array::new();
        for dep in clusters {
            ep_deps_arr.push(dep.as_str());
        }
        insert_feature(&mut features_table, ep_feat, ep_deps_arr, prefix);
    }

    // 7. Granular Cluster Models & Primitives
    let mut first_cl = true;
    for cl in all_cluster_features {
        let prefix = first_cl.then(|| {
            first_cl = false;
            "\n# Granular Cluster Models & Primitives\n"
        });
        insert_feature(&mut features_table, cl.as_str(), Array::new(), prefix);
    }

    let _old = doc.as_table_mut().insert("features", Item::Table(features_table));
    write_if_changed(cargo_toml_path, &doc.to_string())?;
    Ok(())
}
