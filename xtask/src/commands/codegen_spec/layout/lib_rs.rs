use std::path::Path;

use anyhow::Result;
use genco::{lang::rust::Tokens, quote, tokens::quoted};

use super::render;
use crate::util::write_if_changed;

pub(in super::super) fn generate_top_lib_rs(path: &Path, versions: &[(String, String, String)]) -> Result<()> {
    let header = "// AUTO-GENERATED BY cargo xtask codegen-spec - DO NOT EDIT MANUALLY";
    let top_doc = r#"//! **Every Matter cluster, attribute, command, event, and device type: strongly typed at compile time.**
//!
//! `matter-spec` brings the official Connectivity Standards Alliance (CSA) [Matter](https://csa-iot.org/all-solutions/matter/)
//! specification to Rust with exhaustive enums, distinct attribute newtypes, stateful endpoints, conformance
//! validation, and ergonomic unit helpers.
//!
//! # Why `matter-spec`?
//!
//! Working with raw cluster IDs and untyped wire values is error-prone. `matter-spec` gives you
//! compile-time-checked models generated directly from the official CSA specification, organized into one module per
//! supported Matter release.
//!
//! Unlike stack-coupled cluster codegen such as `rs-matter-dm-clusters` (which binds directly to `rs-matter`'s TLV
//! codecs and Interaction Model handler traits), `matter-spec` is completely independent of any network stack,
//! transport, or async runtime. Its only Matter dependency is [`matter-data-model`](model), which it re-exports and
//! converts to and from seamlessly. Drivers and libraries can depend solely on `matter-data-model` (avoiding
//! diamond-dependency conflicts across Matter releases), while a decoupled runtime or stack adapter uses
//! [`SpecRegistry`](registry::SpecRegistry) to look up ACL privileges, access/quality flags, cluster revisions,
//! command responses, and conformance rules by `(ClusterId, MemberId)`.
//!
//! # Features
//!
//! - **Lean typed models & sparse patches:** Every cluster provides a flat state struct with fluent builders, a sparse
//!   patch type for delta updates, a single-attribute enum, and direction-split command and response enums.
//! - **Lossless wire wrappers:** Always-enabled wrappers preserve data versions, global attributes, event numbers,
//!   timestamps, and Manufacturer Extension Identifier (MEI) extra attributes without bloating your domain structs.
//! - **Zero-clone owned conversions:** Owned wire payloads (strings, byte buffers, and vectors) convert into domain
//!   models with zero intermediate clones.
//! - **Exhaustive enums & bitmaps:** Cluster enums are exhaustive for their Matter release so matches are
//!   compiler-verified. Bitmaps provide named flag constants, bitwise operators, and set helpers. Error enums in
//!   [`error`] are also exhaustive by design.
//! - **Static IM metadata & zero-alloc conformance validation:** Read-only [`SpecRegistry`](registry::SpecRegistry)
//!   tables expose ACL privilege levels ([`AccessPrivilege`](registry::AccessPrivilege)),
//!   [`AccessFlags`](registry::AccessFlags), [`QualityFlags`](registry::QualityFlags), cluster revisions, and command
//!   response IDs by `(ClusterId, MemberId)`—and power non-mutating, zero-allocation `Validator` (`validator()`,
//!   `partial_validator()`, [`ValidationMode::Partial`](registry::ValidationMode::Partial) /
//!   [`ValidationMode::FullSnapshot`](registry::ValidationMode::FullSnapshot)) alongside
//!   [`DeviceTypeSpec::view`](traits::DeviceTypeSpec::view).
//! - **Semantic newtypes & ergonomics.** Unit, time, and address types in [`types`] (`Temperature`, `Percent100ths`,
//!   `PowerMw`, `EpochS`, `MatterDate`, `IpAddress`, ...) enforce physical-unit safety via `Deref` on cluster
//!   attributes, inherent [`Optional<Nullable<T>>`](model::Optional) combinators, and `#![no_std]` `jiff`, `time`, and `uom` bridges.
//! - **Boundary dispatch & dynamic schemas.** Feature-gated `#[non_exhaustive]` boundary enums (`ClusterSnapshot`,
//!   `ClusterPatch`, `ClusterAttribute`, `ClusterCommand`, `ClusterCommandResponse`, `ClusterEvent`, `EndpointDevice`,
//!   threshold-boxed above 64 bytes with `Unknown` fallback), [`Described<T>`](dispatch::Described) /
//!   [`Invocation<T>`](dispatch::Invocation) self-describing JSON wrappers, and `FeatureMap`-pruned `schemars` JSON
//!   schemas.
//! - **`#![no_std]` ready.** Uses `alloc` and compiles on bare-metal targets when default features are disabled
//!   (`registry` and `serde` are `#![no_std]` + `alloc`).
//!
//! # Cargo Features
//!
//! Everything is feature-gated so you only compile what your project actually uses:
//!
//! ### 1. Matter Version (Required)
//!
//! Enable at least one version feature (`v1_X`, e.g. `v1_4`); building without one is a compile error. Multiple
//! versions can be enabled side by side with explicit imports. Global attributes, shared types, and extensions are
//! available as soon as a version is selected. When a cluster or global type is identical across multiple Matter
//! releases, those versions re-export the exact same Rust type, so values can be used interchangeably across versions
//! without conversion.
//!
//! ### 2. Clusters and Endpoints
//!
//! Features are layered from coarse to fine. Pick the narrowest tier that fits your use case to keep compile times
//! fast and binaries small:
//!
//! | Tier | Feature / Variable Pattern | Enables |
//! | :--- | :--- | :--- |
//! | All | `all` | Every product domain and unattached cluster |
//! | Product domain (recommended) | `appliances`, `cameras`, `closures`, `energy-management`, `general`, `hvac`, `lighting`, `measurement-and-sensing`, `media`, `network-infrastructure`, `robots` | The domain's endpoints and required clusters |
//! | Unattached clusters | `unattached-clusters` | Standalone and cross-cutting clusters not bound to a specific device type |
//! | Single endpoint | `endpoint-<name>` (e.g. `endpoint-on-off-light`) | One endpoint and its required clusters |
//! | Single cluster (env) | `MATTER_SPEC_CLUSTER_<NAME>=1` (e.g. `MATTER_SPEC_CLUSTER_ON_OFF=1`) | One cluster via build environment or `.cargo/config.toml` `[env]` |
//!
//! ### 3. Capabilities
//!
//! | Feature | Default | Description |
//! | :--- | :---: | :--- |
//! | `std` | Yes | Standard library support across `matter-spec`, `matter-data-model`, `bytes`, and `serde`. |
//! | `registry` | No | `#![no_std]` + `alloc` static `SpecRegistry` metadata (ACL privileges, access/quality flags, cluster revisions, command responses) and zero-alloc `Validator` conformance validation. |
//! | `dispatch` | No | Runtime `*Meta` traits, threshold-boxed boundary enums, and `Described<T>` / `Invocation<T>` self-describing JSON wrappers. |
//! | `serde` | No | `#![no_std]` + `alloc` `Serialize` and `Deserialize` implementations for all models. |
//! | `schemars` | No | Dynamic `FeatureMap`-pruned `JsonSchema` generation via `schemars` (enables `std` and `registry`). |
//! | `deny-unknown-fields` | No | Disallow unrecognized fields in Serde deserialization and Schemars JSON schemas (takes effect when `serde` or `schemars` is enabled). **Library crates must NOT enable this feature**, leave it for leaf binary crates to opt in. |
//! | `jiff` | No | `jiff` conversions for Matter time types. |
//! | `time` | No | `time` crate conversions for Matter time types. |
//! | `uom` | No | `uom` SI unit conversions for physical quantity types in [`types`]. |
//! | `testing` | No | Matter test and example clusters. |
//!
//! # Examples
//!
//! The examples below use the `v1_4` module; substitute the version module you enabled.
//!
//! ### Temperature Conversion, `Optional<Nullable<T>>`, and Bitmaps
//!
//! ```rust
//! # #[cfg(all(feature = "v1_4", feature = "hvac"))]
//! # fn main() {
//! use matter_spec::{
//!     model::{AttributeValue, Nullable, Optional},
//!     types::Temperature,
//!     v1_4::clusters::thermostat::{
//!         RelayStateBitmap,
//!         attributes::OccupiedCoolingSetpoint,
//!     },
//! };
//!
//! // Construct a semantic temperature and wrap it in a cluster attribute
//! let setpoint = OccupiedCoolingSetpoint::new(Temperature::from_celsius(21.5));
//! assert_eq!(setpoint.raw(), 2150); // Matter stores hundredths of °C
//!
//! // Access Temperature helpers directly via Deref
//! let fahrenheit = setpoint.to_fahrenheit();
//! assert!((fahrenheit - 70.7).abs() < 0.1);
//!
//! // Transform Optional<Nullable<T>> fields cleanly
//! let opt_temp: Optional<Nullable<Temperature>> = Optional::Present(Nullable::NonNull(*setpoint));
//! assert_eq!(opt_temp.map_nonnull(Temperature::to_celsius).as_nonnull(), Some(&21.5));
//!
//! // Encode to the wire representation
//! let wire_val: AttributeValue = setpoint.into_value();
//! assert_eq!(wire_val, AttributeValue::I16(2150));
//!
//! // Combine bit flags with standard operators
//! let relay = RelayStateBitmap::HEAT | RelayStateBitmap::FAN;
//! assert!(relay.contains(RelayStateBitmap::HEAT));
//! # }
//! # #[cfg(not(all(feature = "v1_4", feature = "hvac")))]
//! # fn main() {}
//! ```
//!
//! ### Sparse Delta Patches & Lossless Wire Wrappers
//!
//! ```rust
//! # #[cfg(all(feature = "v1_4", cluster_on_off))]
//! # fn main() {
//! use matter_spec::{
//!     prelude::*,
//!     model::DataVersion,
//!     v1_4::clusters::on_off::{OnOff, OnOffCluster, OnOffClusterPatch},
//! };
//!
//! let mut state = OnOffCluster::new(OnOff::Off);
//! let mut patch = OnOffClusterPatch::default();
//! patch.apply_attribute(OnOffCluster::ATTR_ON_OFF, true.into()).unwrap();
//! state.apply_patch(patch);
//! assert_eq!(state.on_off, OnOff::On);
//!
//! // Preserve instance-level wire metadata alongside the lean domain state
//! let wire = state.into_wire().with_data_version(DataVersion::new(42));
//! assert_eq!(wire.on_off, OnOff::On); // direct field access via Deref
//! let model_cluster = matter_spec::model::Cluster::from(wire);
//! assert_eq!(model_cluster.data_version, Optional::Present(DataVersion::new(42)));
//! # }
//! # #[cfg(not(all(feature = "v1_4", cluster_on_off)))]
//! # fn main() {}
//! ```
//!
//! ### Endpoints, Mode Clusters, and Zero-Alloc Validation
//!
//! ```rust
//! # #[cfg(all(feature = "v1_4", feature = "appliances", feature = "registry"))]
//! # fn main() {
//! use matter_spec::{
//!     extensions::ModeClusterExt as _,
//!     v1_4::{prelude::*, registry},
//! };
//!
//! // Build a mode cluster in one line from semantic tags
//! let mode = dishwasher_mode::DishwasherModeCluster::from_tags(
//!     [dishwasher_mode::ModeTag::Normal, dishwasher_mode::ModeTag::Heavy],
//!     dishwasher_mode::ModeTag::Normal,
//! )
//! .unwrap();
//!
//! let dishwasher = Dishwasher::new(operational_state::OperationalStateCluster::new(
//!     None,
//!     None,
//!     vec![operational_state::OperationalStateEnum::Running.into()],
//!     operational_state::OperationalStateEnum::Running,
//!     operational_state::ErrorStateEnum::NoError,
//! ))
//! .with_on_off(on_off::OnOff::On)
//! .with_dishwasher_mode(mode);
//!
//! assert!(dishwasher.on_off.is_present());
//!
//! // Convert to the wire model, validate zero-alloc, inspect via EndpointExt, and round-trip back
//! let ep = dishwasher.clone().into_endpoint(EndpointId::new(1));
//! registry::Validator::full().endpoint(&ep).unwrap();
//! let view = ep.view_as::<Dishwasher>().unwrap().unwrap();
//! assert!(view.on_off().is_some());
//! let roundtrip = Dishwasher::try_from(ep).unwrap();
//! assert_eq!(dishwasher, roundtrip);
//! # }
//! # #[cfg(not(all(feature = "v1_4", feature = "appliances", feature = "registry")))]
//! # fn main() {}
//! ```
"#;

    let any_spec_feats = versions
        .iter()
        .map(|(_, _, feat)| format!("feature = \"{feat}\""))
        .collect::<Vec<_>>()
        .join(", ");
    let compile_err = format!(
        "#[cfg(not(any({any_spec_feats})))]\ncompile_error!(\"matter-spec requires selecting at least one Matter \
         specification version feature (e.g. 'v1_4', 'v1_3', etc.).\");"
    );

    let tokens: Tokens = quote! {
        $header
        $top_doc
        #![no_std]
        #![cfg_attr(docsrs, feature(doc_cfg))]

        $compile_err

        extern crate alloc;
        #[cfg(feature = "std")]
        extern crate std;

        /// Re-export of foundational Matter wire types, models, and identifiers.
        pub use matter_data_model as model;
        /// Zero-copy binary buffer type.
        pub use bytes::Bytes;

        mod macros;
        pub(crate) use macros::*;

        mod __shared;

        pub mod wire;

        pub mod error;

        #[cfg(feature = "registry")]
        pub mod registry;

        pub mod traits;

        pub mod extensions;
        pub mod types;

        #[cfg(feature = "dispatch")]
        pub mod dispatch;

        /// Core ergonomic traits, lossless wire wrappers, and per-version shortcut namespaces.
        pub mod prelude {
            #[cfg(feature = "dispatch")]
            pub use crate::dispatch::*;
            #[cfg(feature = "registry")]
            pub use crate::registry::*;
            pub use crate::{
                error::*,
                extensions::*,
                model::*,
                traits::*,
                types::*,
                wire::*,
            };

            $(for (_, mod_name, feat_name) in versions join ($['\r']) =>
                #[cfg(feature = $(quoted(feat_name)))]
                pub mod $mod_name {
                    pub use crate::$mod_name::shortcuts::*;
                }
            )
        }

        $(for (_, mod_name, feat_name) in versions join ($['\r']) =>
            #[cfg(feature = $(quoted(feat_name)))]
            pub mod $mod_name;
        )
    };

    let rendered = render(tokens)?;
    write_if_changed(path, &rendered)?;
    Ok(())
}
