use std::path::Path;

use anyhow::Result;
use genco::{lang::rust::Tokens, quote, tokens::quoted};

use super::render;
use crate::util::write_if_changed;

pub(in super::super) fn generate_version_clusters_mod(
    path: &Path,
    modules: &[(String, String, String)],
    spec_version: &str,
) -> Result<()> {
    let header =
        format!("// AUTO-GENERATED BY cargo xtask codegen-spec (Matter Spec: {spec_version}) - DO NOT EDIT MANUALLY");
    let intro = format!("//! Matter {spec_version} cluster definitions.");

    let tokens: Tokens = quote! {
        $header
        $intro

        pub use super::globals;

        $(for (mod_name, cluster_feat, orig_name) in modules join ($['\r']) =>
            $(format!("/// {orig_name} cluster domain models."))
            #[cfg(feature = $(quoted(cluster_feat)))]
            pub mod $mod_name;
        )
    };

    let rendered = render(tokens)?;
    write_if_changed(path, &rendered)?;
    Ok(())
}

pub(in super::super) fn generate_endpoints_mod_rs(
    endpoints: &[(String, String, String)],
    version: &str,
) -> Result<String> {
    let header =
        format!("// AUTO-GENERATED BY cargo xtask codegen-spec (Matter Spec: {version}) - DO NOT EDIT MANUALLY");
    let intro = "//! Standard Matter Endpoint definitions (device types) and compile-time conformance models.";

    let tokens: Tokens = quote! {
        $header
        $intro

        $(for (feat, module_name, _) in endpoints join ($['\r']) =>
            #[cfg(feature = $(quoted(feat)))]
            pub mod $module_name;
        )

        $(for (feat, module_name, _) in endpoints join ($['\r']) =>
            #[cfg(feature = $(quoted(feat)))]
            pub use $module_name::*;
        )
    };

    render(tokens)
}

pub(in super::super) fn generate_version_mod(
    path: &Path,
    modules: &[(String, String, String)],
    endpoints: &[(String, String, String)],
    spec_version: &str,
    exact_tag: &str,
    short_sha: &str,
    repo_url: &str,
    repo_folder_url: &str,
) -> Result<()> {
    let header =
        format!("// AUTO-GENERATED BY cargo xtask codegen-spec (Matter Spec: {exact_tag}) - DO NOT EDIT MANUALLY");
    let doc1 = format!(
        "//! Specification domain models for Matter `{exact_tag}` (commit [`{short_sha}`]({repo_folder_url}))."
    );
    let doc2 = "//!".to_owned();
    let doc3 = format!(
        "//! Generated from official CSA Matter XML cluster definitions in \
         [`project-chip/connectedhomeip`]({repo_url})."
    );
    let shortcut_doc = format!("/// Shortcut prelude for Matter {spec_version} clusters and endpoints.");

    let endpoint_conditions: Vec<String> = endpoints
        .iter()
        .map(|(feat, _, _)| format!("feature = \"{feat}\""))
        .collect();
    let endpoint_cfg_str = if endpoint_conditions.is_empty() {
        "#[cfg(feature = \"__never\")]".to_owned()
    } else {
        format!("#[cfg(any({}))]", endpoint_conditions.join(", "))
    };

    let doc_markdown_reason =
        "Upstream CSA Matter XML spec documentation contains raw technical identifiers without code styling";

    let tokens: Tokens = quote! {
        $header
        #![allow(
            clippy::absolute_paths,
            clippy::allow_attributes,
            clippy::arithmetic_side_effects,
            clippy::decimal_literal_representation,
            clippy::doc_markdown,
            clippy::excessive_nesting,
            clippy::indexing_slicing,
            clippy::large_enum_variant,
            clippy::too_many_lines,
            clippy::unnecessary_wraps,
            clippy::unreadable_literal,
            reason = $(quoted(doc_markdown_reason))
        )]

        $doc1
        $doc2
        $doc3

        pub mod clusters;
        #[cfg(feature = "dispatch")]
        pub mod dispatch;
        $(&endpoint_cfg_str)
        pub mod endpoints;
        pub mod globals;
        #[cfg(feature = "registry")]
        pub mod registry;

        #[cfg(feature = "dispatch")]
        pub use dispatch::{
            ClusterAttribute, ClusterCommand, ClusterCommandResponse, ClusterEvent, ClusterPatch, ClusterSnapshot,
            EndpointDevice,
        };

        pub(crate) mod shortcuts {
            #[cfg(feature = "registry")]
            pub use super::registry::{SPEC_REGISTRY, Validator};
            #[cfg(feature = "dispatch")]
            pub use super::dispatch::{
                ClusterAttribute, ClusterCommand, ClusterCommandResponse, ClusterEvent, ClusterPatch, ClusterSnapshot,
                EndpointDevice,
            };

            $(for (mod_name, cluster_feat, _) in modules join ($['\r']) =>
                #[cfg(feature = $(quoted(cluster_feat)))]
                pub use super::clusters::$mod_name;
                #[cfg(feature = $(quoted(cluster_feat)))]
                pub use super::clusters::$mod_name::{$(format!("{}Cluster", snake_to_pascal(mod_name))), $(format!("{}ClusterPatch", snake_to_pascal(mod_name)))};
            )
            $(&endpoint_cfg_str)
            pub use super::endpoints::*;
            pub use super::globals::*;
        }

        $shortcut_doc
        pub mod prelude {
            pub use super::shortcuts::*;
            pub use crate::error::*;
            pub use crate::extensions::{ModeClusterExt, ModeOptionExt};
            pub use crate::model::*;
            pub use crate::traits::{
                AttributeSpec, ClusterSpec, CommandSpec, DeviceTypeSpec, EndpointExt, EventSpec, PartialCluster,
            };
            pub use crate::types::*;
            pub use crate::wire::{GlobalAttributes, WireCluster, WireEvent};
            #[cfg(feature = "registry")]
            pub use crate::validate::{RegistryValidator, ValidationMode};
            #[cfg(feature = "dispatch")]
            pub use crate::dispatch::{CommandMeta, Described, Invocation, MatterDescribe};
        }
    };

    let rendered = render(tokens)?;
    write_if_changed(path, &rendered)?;
    Ok(())
}

fn snake_to_pascal(s: &str) -> String {
    s.split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                None => String::new(),
                Some(first) => first.to_uppercase().chain(chars).collect(),
            }
        })
        .collect()
}
