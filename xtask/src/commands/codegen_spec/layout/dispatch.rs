fn dispatch_cluster_patch_tokens(
    sorted_clusters: &[DispatchClusterEntry],
    snap_any_cfg: &str,
    snap_not_any_cfg: &str,
) -> Tokens {
    quote! {
        /// Polymorphic partial cluster patch across all enabled clusters in this Matter specification version.
        #[derive(Debug, Clone, PartialEq)]
        #[cfg_attr(feature = $(quoted("serde")), derive(Serialize, Deserialize))]
        #[cfg_attr(
            feature = $(quoted("serde")),
            serde(tag = $(quoted("cluster")), content = $(quoted("payload")))
        )]
        #[cfg_attr(feature = $(quoted("schemars")), derive(schemars::JsonSchema))]
        #[non_exhaustive]
        #[rustfmt::skip]
        pub enum ClusterPatch {
            $(for c in sorted_clusters join ($['\r']) =>
                #[cfg($(c.cfg.as_str()))]
                $(if c.has_attributes && c.is_large_patch =>
                    $(c.name.as_str())(Box<clusters::$(c.module_name.as_str())::$(c.struct_name.as_str())Patch>),
                )
                $(if c.has_attributes && !c.is_large_patch =>
                    $(c.name.as_str())(clusters::$(c.module_name.as_str())::$(c.struct_name.as_str())Patch),
                )
                $(if !c.has_attributes =>
                    $(c.name.as_str()),
                )
            )
            /// Forward-compatible fallback for unrecognized clusters.
            Unknown(ClusterId, Vec<model::Attribute>),
        }

        impl From<ClusterPatch> for Cluster {
            fn from(patch: ClusterPatch) -> Self {
                match patch {
                    $(for c in sorted_clusters join ($['\r']) =>
                        #[cfg($(c.cfg.as_str()))]
                        $(if c.has_attributes && c.is_large_patch =>
                            ClusterPatch::$(c.name.as_str())(inner) => Self::new(
                                ClusterId::new($(format_hex_u32(c.cluster_id))),
                                PartialCluster::into_attributes(*inner)
                                    .into_iter()
                                    .map(|(id, val)| model::Attribute::new(id, val))
                                    .collect(),
                            ),
                        )
                        $(if c.has_attributes && !c.is_large_patch =>
                            ClusterPatch::$(c.name.as_str())(inner) => Self::new(
                                ClusterId::new($(format_hex_u32(c.cluster_id))),
                                PartialCluster::into_attributes(inner)
                                    .into_iter()
                                    .map(|(id, val)| model::Attribute::new(id, val))
                                    .collect(),
                            ),
                        )
                        $(if !c.has_attributes =>
                            ClusterPatch::$(c.name.as_str()) => {
                                Self::new(ClusterId::new($(format_hex_u32(c.cluster_id))), Vec::new())
                            }
                        )
                    )
                    ClusterPatch::Unknown(id, attrs) => Self::new(id, attrs),
                }
            }
        }

        #[rustfmt::skip]
        impl ClusterMeta for ClusterPatch {
            #[inline]
            fn cluster_id(&self) -> ClusterId {
                match self {
                    $(for c in sorted_clusters join ($['\r']) =>
                        #[cfg($(c.cfg.as_str()))]
                        $(if c.has_attributes =>
                            Self::$(c.name.as_str())(_) => ClusterId::new($(format_hex_u32(c.cluster_id))),
                        )
                        $(if !c.has_attributes =>
                            Self::$(c.name.as_str()) => ClusterId::new($(format_hex_u32(c.cluster_id))),
                        )
                    )
                    Self::Unknown(id, _) => *id,
                }
            }

            #[inline]
            #[rustfmt::skip]
            fn cluster_name(&self) -> &'static str {
                match self {
                    $(for c in sorted_clusters join ($['\r']) =>
                        #[cfg($(c.cfg.as_str()))]
                        $(if c.has_attributes =>
                            Self::$(c.name.as_str())(_) => {
                                clusters::$(c.module_name.as_str())::$(c.struct_name.as_str())::NAME
                            }
                        )
                        $(if !c.has_attributes =>
                            #[rustfmt::skip]
                            Self::$(c.name.as_str()) => {
                                clusters::$(c.module_name.as_str())::$(c.struct_name.as_str())::NAME
                            }
                        )
                    )
                    Self::Unknown(_, _) => "Unknown",
                }
            }

            #[inline]
            fn is_empty_payload(&self) -> bool {
                match self {
                    $(for c in sorted_clusters join ($['\r']) =>
                        #[cfg($(c.cfg.as_str()))]
                        $(if c.has_attributes && c.is_large_patch =>
                            Self::$(c.name.as_str())(inner) => {
                                PartialCluster::into_attributes((**inner).clone()).is_empty()
                            }
                        )
                        $(if c.has_attributes && !c.is_large_patch =>
                            Self::$(c.name.as_str())(inner) => {
                                PartialCluster::into_attributes(inner.clone()).is_empty()
                            }
                        )
                        $(if !c.has_attributes =>
                            Self::$(c.name.as_str()) => true,
                        )
                    )
                    Self::Unknown(_, attrs) => attrs.is_empty(),
                }
            }
        }

        $(dispatch_cluster_patch_describe_tokens(sorted_clusters, snap_any_cfg, snap_not_any_cfg))
    }
}

