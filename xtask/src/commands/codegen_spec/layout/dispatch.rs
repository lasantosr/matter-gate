        format!("// AUTO-GENERATED BY cargo xtask codegen-spec (Matter Spec: {version}) - DO NOT EDIT MANUALLY");
    let intro = "//! Version-scoped polymorphic [`ClusterCommand`] and [`ClusterCommandResponse`] enums.";

    let v_mod = v_mod_name(version);
    let sorted_clusters = sorted_unique_clusters(clusters);
    let client_clusters: Vec<&DispatchClusterEntry> =
        sorted_clusters.iter().filter(|c| c.has_client_commands).collect();
    let server_clusters: Vec<&DispatchClusterEntry> =
        sorted_clusters.iter().filter(|c| c.has_server_commands).collect();
